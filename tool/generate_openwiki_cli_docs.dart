// Issue #1383 — generates `docs/openwiki/cli.md` from the LIVE command
// registry (the CLI's own --help output), so the per-command docs cannot
// drift from the dispatcher: every command's usage, description, and
// subcommands are captured from `zfa <command> --help`.
//
// Regenerate after any command-surface change:
//   dart run tool/generate_openwiki_cli_docs.dart
import 'dart:convert';
import 'dart:io';

import 'package:zuraffa/src/docs/openwiki_cli_docs.dart';

Future<void> main() async {
  final help = await _zfa(['--help']);

  final names = parseCommandNames(help);
  if (names.isEmpty) {
    stderr.writeln('no commands parsed from --help');
    exit(1);
  }

  final buf = StringBuffer()
    ..writeln('# Openwiki CLI — the command fleet')
    ..writeln()
    ..writeln(
      '<!-- GENERATED by `tool/generate_openwiki_cli_docs.dart` '
      'from the live dispatcher — regenerate, never hand-edit. -->',
    )
    ..writeln()
    ..writeln(
      '- Registry: **${names.length} commands** (as of this '
      'generation — the count is re-emitted on every regeneration, '
      'never pinned by hand).',
    )
    ..writeln(
      '- Exit codes (SPEC 917): `0` success, `1` failure/drift, '
      '`2` usage error. Every non-zero exit ends with a machine-'
      'actionable `--> fix:` line.',
    )
    ..writeln(
      '- Machine envelopes: `--json` emits the '
      '`zuraffa.verdict.v1` document; generated artifacts carry '
      '`proof.v1` receipts under `.zfa/receipts/`.',
    )
    ..writeln();

  for (final name in names) {
    final cmdHelp = await _zfa([name, '--help']);
    buf
      ..writeln('## `zfa $name`')
      ..writeln()
      ..writeln('```');
    buf.writeln(cmdHelp.trimRight());
    buf
      ..writeln('```')
      ..writeln();
  }

  final out = File('docs/openwiki/cli.md');
  await out.parent.create(recursive: true);
  await out.writeAsString(buf.toString());
  stdout.writeln('wrote ${out.path} (${names.length} commands)');
}

Future<String> _zfa(List<String> args) async {
  final result = await Process.run(
    'dart',
    ['run', 'bin/zfa.dart', ...args],
    stdoutEncoding: utf8,
    stderrEncoding: utf8,
  );
  if (result.exitCode != 0) {
    stderr.writeln('zfa ${args.join(" ")} failed: ${result.stderr}');
    exit(1);
  }
  return result.stdout as String;
}
