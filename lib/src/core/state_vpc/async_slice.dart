import 'package:zorphy_annotation/zorphy_annotation.dart';

import '../failure.dart';

part 'async_slice.zorphy.dart';

/// A closed, generic async-load state for one domain slice (v8, ZFA-012).
///
/// [AsyncSlice] is the `@ZorphyUnion` that replaces the v6/v7
/// `SignalResult<T>`-backed [SignalSlice] as the unit of normalized
/// [DomainState] storage. A slice is always in exactly one of four states:
///
///  - [AsyncSlice.idle] — nothing has been requested yet;
///  - [AsyncSlice.loading] — a load is in flight with no data yet;
///  - [AsyncSlice.ready] — data is present, optionally refreshing in place;
///  - [AsyncSlice.failed] — the load failed, optionally with stale data.
///
/// Construct a variant through its root factory (`AsyncSlice<T>.ready(...)`)
/// or the variant's own `fromTrusted`; match exhaustively with the generated
/// `when` / `maybeWhen` extension:
///
/// ```dart
/// final label = slice.when<String>(
///   asyncSliceIdle: (_) => 'idle',
///   asyncSliceLoading: (_) => 'loading',
///   asyncSliceReady: (s) => 'ready:${s.data}',
///   asyncSliceFailed: (s) => 'failed:${s.appFailure.message}',
/// );
/// ```
///
/// This file is **hand-written**; its `part` (`async_slice.zorphy.dart`) is
/// regenerated by `zfa build` and must never be edited by hand.
@ZorphyUnion()
abstract class $AsyncSlice<T> {
  factory $AsyncSlice.idle() => $AsyncSliceIdle<T>();

  factory $AsyncSlice.loading() => $AsyncSliceLoading<T>();

  factory $AsyncSlice.ready(
    T data, {
    @ZorphyDomainBool() bool isRefreshing = false,
  }) => $AsyncSliceReady<T>(data: data, isRefreshing: isRefreshing);

  factory $AsyncSlice.failed(Object? failure, {Object? staleData}) =>
      $AsyncSliceFailed<T>(failure: failure, staleData: staleData);
}

/// The slice has not started loading. Holds no data.
@ZorphyValue()
class $AsyncSliceIdle<T> implements $AsyncSlice<T> {
  const $AsyncSliceIdle();
}

/// A load is in flight and no data is available yet.
@ZorphyValue()
class $AsyncSliceLoading<T> implements $AsyncSlice<T> {
  const $AsyncSliceLoading();
}

/// Data is available. [isRefreshing] marks a background refresh that keeps
/// the current [data] visible while it runs.
@ZorphyValue()
class $AsyncSliceReady<T> implements $AsyncSlice<T> {
  final T data;

  @ZorphyDomainBool()
  final bool isRefreshing;

  const $AsyncSliceReady({required this.data, this.isRefreshing = false});
}

/// The load failed. [staleData] carries the last known value, when any, so a
/// view can keep rendering it through the error.
///
/// WORKAROUND (zuraffa/zorphy#351): zorphy's `@ZorphyUnion` emitter renders a
/// variant field whose type is another union root (`AppFailure`) as
/// `InvalidType`, and drops the `?` on a nullable generic field (`T?` becomes
/// `T`), so both [failure] and [staleData] are stored as `Object?` and
/// re-typed through [appFailure] / [stale]. The public factory still accepts
/// the same values.
@ZorphyValue()
class $AsyncSliceFailed<T> implements $AsyncSlice<T> {
  final Object? failure;

  final Object? staleData;

  const $AsyncSliceFailed({required this.failure, this.staleData});
}

/// Typed views of [AsyncSliceFailed]'s `Object?` fields (see the workaround
/// note on the variant): [appFailure] is the carried [AppFailure], [stale] the
/// last known value.
extension AsyncSliceFailedAccessors<T> on AsyncSliceFailed<T> {
  AppFailure get appFailure => failure as AppFailure;

  T? get stale => staleData as T?;
}
