import 'dart:io';

import '../../mcp/sse_server.dart';
import '../../mcp/streamable_http_server.dart';
import 'di_container.dart';
import 'mcp_stdio_server.dart';
import 'mcp_tool.dart';
import 'mcp_tool_registry.dart';
import 'route_builder.dart';
import 'zuraffa_plugin.dart';

/// Runtime [ZuraffaPlugin] that exposes the host app's [McpTool]s
/// over the Model Context Protocol.
///
/// ## What it does
///
/// During the engine's bootstrap phase, [registerDependencies]
/// populates a [McpToolRegistry] (registered as a singleton in the
/// DI container) with every tool passed to the plugin's constructor.
/// [onInit] then captures the [ZuraffaDIContainer] for later use
/// by [serveStdio] / [serveSse] / [listTools].
///
/// ## Usage (typical generated app)
///
/// Generated by `zfa plugin mcp`, the host `lib/main.dart` becomes:
///
/// ```dart
/// import 'package:zuraffa/zuraffa.dart';
/// import 'package:my_app/src/plugin/mcp_server_plugin.dart';
/// import 'package:my_app/src/mcp/tools.dart';
///
/// void main() async {
///   final engine = ZuraffaEngine()
///     ..register(McpServerPlugin(tools: myMcpTools));
///   await engine.bootstrap();
///
///   // Run the stdio MCP server. Blocks forever.
///   await engine['mcp']!.serveStdio();
/// }
/// ```
///
/// ## Design notes
///
/// - The plugin does NOT auto-start any server by default. The host
///   app decides when to start the loop (typically at the end of
///   `main()` after `engine.bootstrap()` completes). Pass
///   `autoStartStdio: true` to start the loop in [onInit].
/// - The `routes` getter returns an empty map — the MCP plugin does
///   not contribute to the host app's route table.
/// - `pluginId` defaults to `'mcp'`; pass a custom id if you need
///   multiple MCP server plugins in the same engine (rare).
class McpServerPlugin extends ZuraffaPlugin {
  @override
  final String pluginId;

  /// The tools this plugin exposes. Held immutably — the
  /// [McpToolRegistry] in DI is the live source of truth after
  /// bootstrap.
  final List<McpTool> tools;

  /// If `true`, [onInit] automatically starts the stdio server.
  /// Useful for bin-only apps that exist solely to serve MCP.
  final bool autoStartStdio;

  /// If non-null, [onInit] automatically starts the SSE server on
  /// the given port. Pair with [sseAuthToken] for remote agents.
  final int? autoStartSsePort;

  /// Bearer token for the auto-started SSE server. Ignored unless
  /// [autoStartSsePort] is set.
  final String? sseAuthToken;

  /// Maximum number of concurrent SSE sessions (forwarded to
  /// [McpSseServer]). `null` (default) means unbounded. Requirement #3.
  final int? maxSseConnections;

  /// Per-token tool allowlists forwarded to [McpSseServer] (requirement #3).
  /// A token maps to the set of tool names it may invoke; anonymous
  /// requests are denied tool calls when any allowlist is configured.
  final Map<String, Set<String>>? sseToolAllowlist;

  /// If non-null, [onInit] automatically starts the Streamable HTTP
  /// server (issue #2046) on the given port. Pair with [httpAuthToken]
  /// for anything beyond loopback consumption.
  final int? autoStartHttpPort;

  /// Bearer token for the Streamable HTTP server. Forwarded to
  /// [McpStreamableHttpServer] for both the auto-started and explicit
  /// [serveHttp] servers. Required when the HTTP server binds
  /// non-loopback.
  final String? httpAuthToken;

  /// Per-token tool allowlists forwarded to the Streamable HTTP
  /// server (same shape as [sseToolAllowlist]).
  final Map<String, Set<String>>? httpToolAllowlist;

  /// When `true`, the Streamable HTTP server binds `0.0.0.0` instead
  /// of the loopback default. Refused without [httpAuthToken].
  final bool httpBindAll;

  /// Captured during [onInit] for later use by [serveStdio] /
  /// [serveSse] / [listTools]. `null` before bootstrap completes.
  ZuraffaDIContainer? _di;

  /// The [McpSseServer] started by [serveSse], or `null` before a
  /// start (or after it has been stopped). Retained so callers and
  /// tests can invoke `stop()` after `await plugin.serveSse(...)`.
  McpSseServer? _sseServer;

  /// The [McpStreamableHttpServer] started by [serveHttp], or `null`
  /// before a start (or after it has been stopped). Retained so
  /// callers and tests can invoke `stop()` after
  /// `await plugin.serveHttp(...)` returns.
  McpStreamableHttpServer? _httpServer;

  McpServerPlugin({
    this.pluginId = 'mcp',
    List<McpTool>? tools,
    this.autoStartStdio = false,
    this.autoStartSsePort,
    this.sseAuthToken,
    this.maxSseConnections,
    this.sseToolAllowlist,
    this.autoStartHttpPort,
    this.httpAuthToken,
    this.httpToolAllowlist,
    this.httpBindAll = false,
  }) : tools = List<McpTool>.unmodifiable(tools ?? const []);

  @override
  void registerDependencies(ZuraffaDIContainer di) {
    final registry = McpToolRegistry();
    for (final tool in tools) {
      registry.register(tool);
    }
    // The runtime ZuraffaPlugin contract is sync (void), so we
    // bypass the async override path in ZuraffaDIContainer.registerSingleton
    // and manipulate GetIt directly. In production the type is never
    // registered yet; in tests with a shared GetIt.instance the prior
    // registration is removed synchronously before re-registering.
    final getIt = di.getIt;
    if (getIt.isRegistered<McpToolRegistry>()) {
      // unregister's side effect is synchronous; the returned Future
      // is for onDispose callbacks we don't use.
      getIt.unregister<McpToolRegistry>();
    }
    getIt.registerSingleton<McpToolRegistry>(registry);
  }

  @override
  Future<void> onInit(ZuraffaDIContainer di) async {
    _di = di;
    if (autoStartStdio) {
      // Start stdio server without awaiting — serveStdio() blocks forever
      // in production, so we capture the future for error reporting but
      // don't block engine bootstrap. SSE startup remains awaited.
      serveStdio().catchError((e, st) {
        stderr.writeln('[mcp] serveStdio error: $e\n$st');
      });
    } else if (autoStartSsePort != null) {
      await serveSse(port: autoStartSsePort!, authToken: sseAuthToken);
    } else if (autoStartHttpPort != null) {
      await serveHttp(port: autoStartHttpPort!);
    }
  }

  @override
  Future<void> onDispose(ZuraffaDIContainer di) async {
    // Engine shutdown must close the HTTP listener: unlike the stdio
    // server (which dies with the process), a bound socket outlives the
    // engine unless it is stopped here.
    await _httpServer?.stop();
  }

  @override
  Map<String, ZuraffaRouteHandler> get routes => const {};

  /// Returns the live [McpToolRegistry] from the DI container.
  ///
  /// Throws [StateError] if called before [onInit] has run (i.e.
  /// before the engine has bootstrapped). Pre-bootstrap callers
  /// can inspect the static [tools] list instead.
  McpToolRegistry get registry {
    final di = _di;
    if (di == null) {
      throw StateError(
        'McpServerPlugin cannot resolve its registry before the '
        'engine has bootstrapped (onInit has not run yet).',
      );
    }
    return di.get<McpToolRegistry>();
  }

  /// Lists the tools currently registered. Pre-bootstrap, returns
  /// the static [tools] list; post-bootstrap, returns the live
  /// registry contents (which may differ if the host app added
  /// tools via `registry.register(...)` after bootstrap).
  List<McpTool> listTools() {
    if (_di == null) return List<McpTool>.unmodifiable(tools);
    return registry.allTools;
  }

  /// Starts the stdio MCP server. Blocks forever in production
  /// (stdin is held open); in tests with an injected stream it
  /// returns when the stream ends.
  ///
  /// Throws [StateError] if called before bootstrap.
  Future<void> serveStdio({
    String serverName = 'zuraffa-app-mcp',
    String serverVersion = '1.0.0',
  }) async {
    final di = _requireDi();
    final reg = di.get<McpToolRegistry>();
    final server = McpStdioServer(
      registry: reg,
      serverName: serverName,
      serverVersion: serverVersion,
    );
    await server.run();
  }

  /// The [McpSseServer] started by [serveSse], or `null` if none has
  /// been started. This reference is retained even after the server is
  /// stopped or if [serveSse] fails during startup. Use
  /// [McpSseServer.isRunning] to check whether the server is currently
  /// running. Callers and tests can invoke `stop()` on the returned
  /// instance after `await plugin.serveSse(...)` returns.
  McpSseServer? get sseServer => _sseServer;

  /// The [McpStreamableHttpServer] started by [serveHttp], or `null`
  /// if none has been started (or after it has been stopped). Use
  /// [McpStreamableHttpServer.isRunning] / [McpStreamableHttpServer.stop]
  /// on the returned instance.
  McpStreamableHttpServer? get httpServer => _httpServer;

  /// Starts the Streamable HTTP MCP server (issue #2046) on [port].
  /// Returns when the server is bound (not when it shuts down).
  ///
  /// Binds loopback by default; pass [bindAll: true] to expose the
  /// server beyond loopback — refused unless an auth token is
  /// configured (explicitly or via the plugin's [httpAuthToken]).
  ///
  /// Throws [StateError] if called before bootstrap, or while another
  /// HTTP server started by this plugin is still running — a second
  /// bind would orphan the first listener (it would keep serving with
  /// its original token and allowlist, unreachable through
  /// [httpServer]). A failed bind leaves the existing [httpServer]
  /// reference untouched: the new server is retained only after a
  /// successful start.
  Future<void> serveHttp({
    int port = 8373,
    String? authToken,
    bool bindAll = false,
    String serverName = 'zuraffa-app-mcp',
    String serverVersion = '1.0.0',
  }) async {
    final di = _requireDi();
    final running = _httpServer;
    if (running != null && running.isRunning) {
      throw StateError(
        'serveHttp: an HTTP MCP server is already running on port '
        '${running.port}. Call httpServer.stop() before starting '
        'another.',
      );
    }
    final reg = di.get<McpToolRegistry>();
    final resolvedToken = authToken ?? httpAuthToken;
    final http = McpStreamableHttpServer(
      registry: reg,
      serverName: serverName,
      serverVersion: serverVersion,
      authToken: resolvedToken,
      tokenToolAllowlist: httpToolAllowlist,
      bindAll: bindAll || httpBindAll,
    );
    await http.start(port: port);
    _httpServer = http;
  }

  /// Starts an SSE MCP server on [port]. Returns when the server
  /// is bound (not when it shuts down).
  ///
  /// [authToken] gates remote connections; loopback connections
  /// are always allowed. When `null`, any client can connect.
  ///
  /// Throws [StateError] if called before bootstrap.
  Future<void> serveSse({
    int port = 8372,
    String? authToken,
    String serverName = 'zuraffa-app-mcp',
    String serverVersion = '1.0.0',
  }) async {
    final di = _requireDi();
    final reg = di.get<McpToolRegistry>();
    final sse = McpSseServer(
      registry: reg,
      serverName: serverName,
      serverVersion: serverVersion,
      authToken: authToken,
      maxConnections: maxSseConnections,
      toolAllowlist: sseToolAllowlist,
    );
    _sseServer = sse;
    await sse.start(port: port);
  }

  ZuraffaDIContainer _requireDi() {
    final di = _di;
    if (di == null) {
      throw StateError(
        'McpServerPlugin cannot serve before the engine has '
        'bootstrapped (onInit has not run yet).',
      );
    }
    return di;
  }
}
