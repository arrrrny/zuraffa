/// TreeFacts — the immutable snapshot of the live widget tree the
/// runtime skin-contract auditor audits against (issue #1102).
///
/// The 006-login-skin pilot proved the shape: the auditor walks the
/// element tree once per audited frame and collects exactly what the
/// contract rows need — the rendered texts, the `zfa:` anchor keys,
/// whether a progress indicator is on screen, and the platform the
/// THEME reports (pilot lesson 8: rows encode platform gating read
/// from `Theme.of(context).platform`, the same override-aware source
/// the layout gates on, so auditor and skin can never disagree about
/// platform).
///
/// Pure Dart on purpose: the Flutter-side `inspectTree(Element)`
/// walker lives in the EMITTED kit (`skin/skin_contract_auditor.dart`,
/// generated by `SkinContractKitBuilder`), while the facts type and
/// every row that consumes it stay in the framework — importable by
/// generated apps through `package:zuraffa/skin.dart` (Constitution
/// VII: `lib/` never imports Flutter).
library;

/// The platform vocabulary of the adaptive skin contract — the labels
/// the SKIN lane's `adaptive_slots` declare (issue #1000).
enum SkinTargetPlatform {
  /// Phone-width layout (the slot every platform falls back to).
  mobile,

  /// The iOS platform override (home-indicator safe area).
  ios,

  /// The Android platform override (surface-tone layout).
  android,

  /// The macOS platform override (trailing title-bar alignment).
  macos,

  /// Any other platform (windows/linux/fuchsia/web): the auditor
  /// treats it as ungated — never a phantom violation.
  other;

  /// The stable machine name (matches the `adaptive_slots` labels).
  String get label => switch (this) {
    SkinTargetPlatform.mobile => 'mobile',
    SkinTargetPlatform.ios => 'ios',
    SkinTargetPlatform.android => 'android',
    SkinTargetPlatform.macos => 'macos',
    SkinTargetPlatform.other => 'other',
  };
}

/// An immutable snapshot of what the live tree renders.
///
/// Value equality matters: the emitted auditor compares consecutive
/// snapshots to skip no-op audits, and the banner only rebuilds when
/// the facts (and therefore the verdicts) actually changed — the
/// pilot's chaos edit (`Continue with Google` → `Continue with
/// Goggle`) must produce a NEW snapshot so the violation surfaces on
/// the FIRST audited frame.
class TreeFacts {
  /// Creates a snapshot, defensively copying [texts] and [anchors] —
  /// the tree keeps moving after the walk, and mutable input buffers
  /// (the emitted walker's accumulators, test seams) must never leak
  /// into an immutable snapshot.
  TreeFacts({
    List<String> texts = const [],
    Set<String> anchors = const {},
    this.hasProgressIndicator = false,
    this.platform,
  }) : _texts = List.unmodifiable(texts),
       _anchors = Set.unmodifiable(anchors);

  /// The empty snapshot (no walk happened / empty subtree). The only
  /// const constructor: constant inputs only.
  const TreeFacts.empty()
    : _texts = const [],
      _anchors = const {},
      hasProgressIndicator = false,
      platform = null;

  final List<String> _texts;
  final Set<String> _anchors;

  /// The rendered texts, in walk order.
  List<String> get texts => List.unmodifiable(_texts);

  /// The `zfa:` anchor keys present in the tree (typed anchor
  /// protocol — `ZfaAnchors.keyFor`).
  Set<String> get anchors => Set.unmodifiable(_anchors);

  /// Whether any progress indicator (loading scrim) is on screen —
  /// the contract the pilot used to catch the real macOS bug
  /// (lesson 1: mobile-only testing had pumped only the mobile slot,
  /// so the macOS layout shipped with NO loading scrim).
  final bool hasProgressIndicator;

  /// The platform the THEME reports at the audited root — the
  /// override-aware gating source (lesson 8). Null when unknown
  /// (rows gated to a platform then SKIP, never flag).
  final SkinTargetPlatform? platform;

  /// Machine-readable shape (receipts / diagnostics).
  Map<String, Object?> toJson() => {
    'texts': List<String>.of(_texts),
    'anchors': List<String>.of(_anchors)..sort(),
    'hasProgressIndicator': hasProgressIndicator,
    if (platform != null) 'platform': platform!.label,
  };

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is TreeFacts &&
          other.hasProgressIndicator == hasProgressIndicator &&
          other.platform == platform &&
          _listEquals(other._texts) &&
          _setEquals(other._anchors);

  @override
  int get hashCode => Object.hash(
    Object.hashAllUnordered(_anchors),
    Object.hashAll(_texts),
    hasProgressIndicator,
    platform,
  );

  bool _listEquals(List<String> other) {
    if (_texts.length != other.length) return false;
    for (var i = 0; i < _texts.length; i++) {
      if (_texts[i] != other[i]) return false;
    }
    return true;
  }

  bool _setEquals(Set<String> other) {
    if (_anchors.length != other.length) return false;
    return _anchors.every(other.contains);
  }

  @override
  String toString() =>
      'TreeFacts(texts: ${_texts.length}, anchors: ${_anchors.length}, '
      'progress: $hasProgressIndicator, platform: ${platform?.label})';
}
