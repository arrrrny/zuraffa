/// `TddExampleWriter` — writes `test/tdd_example_test.dart` for a
/// generated Flutter project when the user passes `--tdd-example`.
library;

import 'dart:io';

class TddExampleWriter {
  const TddExampleWriter();

  String render(String appName) {
    return '''// Generated by `zfa setup --tdd-example`. Demonstrates the red half
// of the red->green TDD loop. To turn this green, implement the
// `greeting` getter on AppContainer to return a non-null String.
import 'package:flutter_test/flutter_test.dart';
import 'package:$appName/app.dart';

void main() {
  group('tdd example', () {
    test('the AppContainer exposes a non-null greeting', () {
      final container = AppContainer();
      // This assertion will fail with `Expected: a value <> null
      // Actual: null` until the `greeting` getter is implemented on
      // AppContainer — an honest red, not a compile error.
      expect(container.greeting, isNotNull);
    });
  });
}
''';
  }

  Future<String?> write(
    String projectRoot,
    String appName, {
    bool dryRun = false,
  }) async {
    final dir = Directory('$projectRoot/test');
    final file = File('${dir.path}/tdd_example_test.dart');
    final content = render(appName);

    if (dryRun) {
      return file.path;
    }

    if (await file.exists()) {
      return null;
    }

    await dir.create(recursive: true);
    await file.writeAsString(content);
    return file.path;
  }
}
