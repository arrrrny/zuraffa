/// `SmokeTestWriter` — writes `test/bootstrap_smoke_test.dart` for a
/// generated project.
///
/// Issue #664: the writer is project-flavor aware. A Flutter project gets
/// the Flutter smoke test (`package:flutter_test` + the zfa-generated app
/// module assertion); a pure Dart package gets a Dart-compatible smoke test
/// that only relies on `package:test` — the runner recorded in the project's
/// `tdd-profile.md` — so `dart test` is green on day zero instead of failing
/// with "Couldn't resolve the package 'flutter_test'".
library;

import 'dart:io';

import 'app_module_writer.dart';

class SmokeTestWriter {
  /// Whether the target project is a Flutter project.
  ///
  /// Defaults to `true` to preserve the historical Flutter-first behavior
  /// for callers that generate into Flutter scaffolds (e.g. `zfa setup`).
  const SmokeTestWriter({this.isFlutter = true});

  final bool isFlutter;

  String render(String appName) =>
      isFlutter ? _renderFlutter(appName) : _renderPureDart();

  /// Pure Dart smoke test (issue #664): no `package:flutter_test`, no app
  /// module — only `package:test`, matching the project's `dart_test.yaml`
  /// and the `tdd-profile.md` runner (`package:test (^1.24.0)`).
  String _renderPureDart() {
    return '''// Generated by `zfa tdd init`. Do not edit; re-run `zfa tdd init` to refresh.
import 'package:test/test.dart';

void main() {
  group('bootstrap smoke', () {
    test('the pure Dart test runner is wired and green on day zero', () {
      // A pure Dart package has no zfa-generated app module or DI container
      // to construct, so the day-zero smoke check proves the baseline
      // itself is wired: `dart test` resolves package:test (the runner
      // recorded in .specify/memory/tdd-profile.md) and this assertion
      // runs to green (spec 041 FR-001; issue #664).
      expect(true, isTrue);
    });
  });
}
''';
  }

  String _renderFlutter(String appName) {
    // Issue #626 naming contract: the container symbol derives from the
    // app name (`zik_zak_tdd` -> `ZikZakTddContainer`). The symbol comes
    // from the same helper that renders lib/app.dart, so the assertion and
    // the emitted app module can never drift apart again.
    final containerSymbol = AppModuleWriter.containerSymbolFor(appName);
    return '''// Generated by `zfa setup`. Do not edit; re-run `zfa tdd init` to refresh.
import 'package:flutter_test/flutter_test.dart';
import 'package:$appName/app.dart';

void main() {
  group('bootstrap smoke', () {
    test('the app module and DI container can be constructed', () {
      // The generated app module (lib/app.dart) exposes a zfa-generated
      // DI container named after the app: $containerSymbol. Constructing
      // it without throwing proves the DI graph is satisfiable at runtime
      // — the day-zero precondition for any TDD work on the generated app
      // (spec 041 FR-001; the container is emitted by `zfa setup`,
      // issue #626).
      final container = $containerSymbol();
      expect(container, isNotNull);
    });
  });
}
''';
  }

  Future<String?> write(
    String projectRoot,
    String appName, {
    bool dryRun = false,
  }) async {
    final dir = Directory('$projectRoot/test');
    final file = File('${dir.path}/bootstrap_smoke_test.dart');
    final content = render(appName);

    if (dryRun) {
      return file.path;
    }

    if (await file.exists()) {
      return null;
    }

    await dir.create(recursive: true);
    await file.writeAsString(content);
    return file.path;
  }
}
