/// `DartTestYamlWriter` — writes `dart_test.yaml` at a generated project's
/// root.
library;

import 'dart:io';

class DartTestYamlWriter {
  const DartTestYamlWriter();

  static const String content = '''# dart_test.yaml — generated by `zfa setup`.
# Configures the dart/flutter test runner.

color: true
concurrency: 4
timeout: 30s
retry: 0
pause_after_load: false
''';

  Future<String?> write(String projectRoot, {bool dryRun = false}) async {
    final file = File('$projectRoot/dart_test.yaml');

    if (dryRun) {
      return file.path;
    }

    if (await file.exists()) {
      final existing = await file.readAsString();
      if (existing.trim() == content.trim()) {
        return null;
      }
      return null;
    }

    await file.writeAsString(content);
    return file.path;
  }
}
