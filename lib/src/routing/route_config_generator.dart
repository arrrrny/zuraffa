/// Generates the route configuration artifacts from validated @Route
/// declarations (spec 033 FR-002, FR-005, FR-007, FR-008).
///
/// Output is a deterministic, hand-emitted Dart source file
/// (`zfa_router.g.dart`) targeting `package:go_router`, plus deep-link
/// side files when `deepLinkAware` routes exist. Determinism (sorted
/// entries, stable formatting) guarantees idempotent regeneration.
library;

import 'route_model.dart';

class GeneratedRouteConfig {
  const GeneratedRouteConfig({
    required this.routerSource,
    required this.deepLinkFiles,
  });

  /// Content of `lib/src/routing/zfa_router.g.dart`.
  final String routerSource;

  /// Path (relative to the project root) → content of deep-link artifacts.
  final Map<String, String> deepLinkFiles;
}

class RouteConfigGenerator {
  RouteConfigGenerator._();

  static const String _header = '''
// GENERATED CODE - DO NOT MODIFY BY HAND
//
// Generated by `zfa build` from @Route annotations (spec 033).
// Every route here was declared with a @Route annotation on a View class.

import 'package:go_router/go_router.dart';

import 'package:zuraffa/zuraffa.dart';
''';

  /// Generates the router source + deep-link artifacts.
  ///
  /// [packageName] is the target package name (from its pubspec.yaml),
  /// used for view/guard import URIs. [guardIndex] maps guard class names
  /// to their lib-relative import URIs (from the scanner's class index).
  static GeneratedRouteConfig generate({
    required String packageName,
    required List<RouteDeclaration> routes,
    required List<RouteRedirectRule> redirects,
    required Map<String, String> guardIndex,
  }) {
    final sortedRoutes = List<RouteDeclaration>.from(routes)
      ..sort((a, b) {
        final byPath = a.path.compareTo(b.path);
        if (byPath != 0) return byPath;
        return a.name.compareTo(b.name);
      });
    final sortedRedirects = List<RouteRedirectRule>.from(redirects)
      ..sort((a, b) => a.from.compareTo(b.from));

    final buffer = StringBuffer(_header);

    // Imports: views + guards (deduplicated, sorted).
    final imports = <String>{};
    for (final route in sortedRoutes) {
      imports.add("import 'package:$packageName/${route.importUri}';");
      for (final guard in route.middleware) {
        final guardUri = guardIndex[guard];
        if (guardUri != null) {
          imports.add("import 'package:$packageName/$guardUri';");
        }
      }
    }
    final importLines = imports.toList()..sort();
    if (importLines.isNotEmpty) {
      buffer.writeln();
      for (final line in importLines) {
        buffer.writeln(line);
      }
    }

    buffer.writeln();

    // RouteParams classes.
    final paramsClasses = <String>[];
    for (final route in sortedRoutes) {
      final source = _paramsClassFor(route);
      if (source != null) paramsClasses.add(source);
    }

    // Route tree.
    buffer.writeln('/// All routes compiled from @Route annotations.');
    if (sortedRoutes.isEmpty) {
      buffer.writeln('final List<RouteBase> zfaRoutes = [];');
    } else {
      buffer.writeln('final List<RouteBase> zfaRoutes = [');
      _emitRouteEntries(buffer, sortedRoutes, indent: '  ');
      buffer.writeln('];');
    }

    // Redirects.
    buffer.writeln();
    buffer.writeln(
        '/// Redirect rules compiled from @Route.redirect annotations.');
    if (sortedRedirects.isEmpty) {
      buffer.writeln('final List<RouteBase> zfaRouteRedirects = [];');
    } else {
      buffer.writeln('final List<RouteBase> zfaRouteRedirects = [');
      for (final redirect in sortedRedirects) {
        buffer.writeln(
          "  GoRoute(path: '${redirect.from}', "
          "redirect: (_, __) => '${redirect.to}'),",
        );
      }
      buffer.writeln('];');
    }

    // Guard helper.
    final guardRedirectDefaults = sortedRoutes
        .map((r) => r.guardRedirect)
        .whereType<String>()
        .toSet();
    final defaultDenyPath = guardRedirectDefaults.isEmpty
        ? '/login'
        : guardRedirectDefaults.first;
    buffer.writeln();
    buffer.writeln('/// Adapts a [GoRouterState] into the pure-Dart');
    buffer.writeln('/// [ZuraffaRouteState] consumed by guards.');
    buffer.writeln('ZuraffaRouteState _zfaRouteState(GoRouterState state) {');
    buffer.writeln('  return ZuraffaRouteState(');
    buffer.writeln('    location: state.uri.toString(),');
    buffer.writeln('    path: state.fullPath ?? state.matchedLocation,');
    buffer.writeln('    matchedLocation: state.matchedLocation,');
    buffer.writeln('    queryParameters: state.uri.queryParameters,');
    buffer.writeln('    pathParameters: state.pathParameters,');
    buffer.writeln('    extra: state.extra,');
    buffer.writeln('  );');
    buffer.writeln('}');
    buffer.writeln();
    buffer.writeln('/// Runs [guards] before route activation; returns the '
        'first denied');
    buffer.writeln("/// guard's [ZuraffaRouteGuard.onRejected] path, or null "
        'to proceed.');
    buffer.writeln('Future<String?> zfaGuardRedirect(');
    buffer.writeln('  List<ZuraffaRouteGuard> guards,');
    buffer.writeln('  ZuraffaRouteState state,');
    buffer.writeln(') async {');
    buffer.writeln('  for (final guard in guards) {');
    buffer.writeln('    if (!await guard.canActivate(state)) {');
    buffer.writeln('      return guard.onRejected(state);');
    buffer.writeln('    }');
    buffer.writeln('  }');
    buffer.writeln('  return null;');
    buffer.writeln('}');
    buffer.writeln();
    buffer.writeln('/// Default deny path (from @Route(guardRedirect: ...)) '
        'recommended');
    buffer.writeln('/// for guard [ZuraffaRouteGuard.onRejected] '
        'implementations.');
    buffer.writeln(
        "const String zfaDefaultGuardDenyPath = '$defaultDenyPath';");

    // RouteParams classes.
    if (paramsClasses.isNotEmpty) {
      buffer.writeln();
      for (final source in paramsClasses) {
        buffer.write(source);
      }
    }

    final deepLinkFiles = _deepLinkFiles(sortedRoutes);

    return GeneratedRouteConfig(
      routerSource: buffer.toString(),
      deepLinkFiles: deepLinkFiles,
    );
  }

  // ------------------------------------------------------------------
  // Route tree emission
  // ------------------------------------------------------------------

  static void _emitRouteEntries(
    StringBuffer buffer,
    List<RouteDeclaration> routes, {
    required String indent,
  }) {
    final byName = {for (final route in routes) route.name: route};
    final childrenOf = <String, List<RouteDeclaration>>{};
    final topLevel = <RouteDeclaration>[];

    for (final route in routes) {
      final parent = route.parent;
      if (parent != null && byName.containsKey(parent)) {
        childrenOf.putIfAbsent(parent, () => []).add(route);
      } else {
        topLevel.add(route);
      }
    }

    for (final route in topLevel) {
      final children = childrenOf[route.name] ?? const <RouteDeclaration>[];
      if (route.isShell) {
        _emitShellRoute(buffer, route, children, childrenOf, indent,
            parentPath: null);
      } else if (children.isNotEmpty) {
        // A non-shell route with children nests them as sub-routes.
        _emitGoRoute(buffer, route, childrenOf, indent, parentPath: null);
      } else {
        _emitGoRoute(buffer, route, childrenOf, indent, parentPath: null);
      }
    }
  }

  static void _emitShellRoute(
    StringBuffer buffer,
    RouteDeclaration route,
    List<RouteDeclaration> children,
    Map<String, List<RouteDeclaration>> childrenOf,
    String indent, {
    String? parentPath,
  }) {
    buffer.writeln('$indent ShellRoute(');
    buffer.writeln('$indent   builder: (context, state, child) {');
    _emitBind(buffer, route, '$indent     ');
    if (route.viewAcceptsChild) {
      buffer.writeln(
          '$indent     return ${route.viewClassName}(child: child);');
    } else {
      buffer.writeln('$indent     return const ${route.viewClassName}();');
    }
    buffer.writeln('$indent   },');
    if (children.isNotEmpty) {
      buffer.writeln('$indent   routes: [');
      for (final child in children) {
        if (child.isShell) {
          _emitShellRoute(
            buffer,
            child,
            childrenOf[child.name] ?? const <RouteDeclaration>[],
            childrenOf,
            '$indent     ',
            parentPath: _fullPath(route, parentPath),
          );
        } else {
          _emitGoRoute(
            buffer,
            child,
            childrenOf,
            '$indent     ',
            parentPath: _fullPath(route, parentPath),
          );
        }
      }
      buffer.writeln('$indent   ],');
    }
    buffer.writeln('$indent ),');
  }

  static void _emitGoRoute(
    StringBuffer buffer,
    RouteDeclaration route,
    Map<String, List<RouteDeclaration>> childrenOf,
    String indent, {
    String? parentPath,
  }) {
    // go_router nests by joining parent + child paths; children must use
    // RELATIVE paths (no leading slash).
    var routePath = route.path;
    final fullPath = _fullPath(route, parentPath);
    if (parentPath != null) {
      if (routePath.startsWith('$parentPath/')) {
        routePath = routePath.substring(parentPath.length + 1);
      } else {
        routePath = routePath.replaceFirst('/', '');
      }
    }

    buffer.writeln('$indent GoRoute(');
    buffer.writeln("$indent   path: '$routePath',");
    buffer.writeln("$indent   name: '${route.name}',");
    if (route.middleware.isNotEmpty) {
      final guards = route.middleware.map((guard) => 'const $guard()').join(', ');
      buffer.writeln(
          '$indent   redirect: (context, state) => zfaGuardRedirect(');
      buffer.writeln('$indent     [$guards],');
      buffer.writeln('$indent     _zfaRouteState(state),');
      buffer.writeln('$indent   ),');
    }
    buffer.writeln('$indent   builder: (context, state) {');
    _emitBind(buffer, route, '$indent     ');
    buffer.writeln('$indent     return const ${route.viewClassName}();');
    buffer.writeln('$indent   },');
    final children = childrenOf[route.name] ?? const <RouteDeclaration>[];
    if (children.isNotEmpty) {
      buffer.writeln('$indent   routes: [');
      for (final child in children) {
        _emitGoRoute(
          buffer,
          child,
          childrenOf,
          '$indent       ',
          parentPath: fullPath,
        );
      }
      buffer.writeln('$indent   ],');
    }
    buffer.writeln('$indent ),');
  }

  static String _fullPath(RouteDeclaration route, String? parentPath) {
    if (parentPath == null) return route.path;
    if (route.path.startsWith('$parentPath/')) return route.path;
    return '$parentPath${route.path}';
  }

  static void _emitBind(
    StringBuffer buffer,
    RouteDeclaration route,
    String indent,
  ) {
    if (route.pathParameterNames.isEmpty && route.query.isEmpty) return;
    final paramsClass = _paramsClassName(route);
    buffer.writeln('$indent ZfaRouteParams.bind(');
    buffer.writeln('$indent   $paramsClass.fromMaps(');
    buffer.writeln('$indent     state.pathParameters,');
    buffer.writeln('$indent     state.uri.queryParameters,');
    buffer.writeln('$indent   ),');
    buffer.writeln('$indent );');
  }

  // ------------------------------------------------------------------
  // RouteParams emission
  // ------------------------------------------------------------------

  /// RouteParams classes derive from the View class name (unique per
  /// view, matching the DDA RouteGenerator convention).
  static String _paramsClassName(RouteDeclaration route) =>
      '${route.viewClassName}RouteParams';

  static String? _paramsClassFor(RouteDeclaration route) {
    // Emit whenever the route HAS path or query parameters — the params
    // map only TYPES them (untyped path params default to String).
    if (route.pathParameterNames.isEmpty && route.query.isEmpty) {
      return null;
    }

    final className = _paramsClassName(route);
    final pathParams = route.pathParameterNames;

    final buffer = StringBuffer();
    buffer.writeln('/// Typed parameters for `${route.path}`.');
    buffer.writeln('class $className extends ZfaRouteParams {');
    buffer.writeln('  const $className({');
    for (final param in pathParams) {
      buffer.writeln('    required this.$param,');
    }
    for (final query in route.query) {
      buffer.writeln('    this.$query,');
    }
    buffer.writeln(
        '    super.pathParameters = const <String, String>{},');
    buffer.writeln(
        '    super.queryParameters = const <String, String>{},');
    buffer.writeln('  });');

    buffer.writeln();
    buffer.writeln('  factory $className.fromMaps(');
    buffer.writeln('    Map<String, String> pathParameters,');
    buffer.writeln('    Map<String, String> queryParameters,');
    buffer.writeln('  ) {');
    buffer.writeln('    return $className(');
    for (final param in pathParams) {
      final type = route.params[param] ?? 'String';
      final helper = switch (type) {
        'int' => 'intParam',
        'double' => 'doubleParam',
        'bool' => 'boolParam',
        _ => 'stringParam',
      };
      buffer.writeln(
          "      $param: ZfaRouteParams.$helper(pathParameters, '$param'),");
    }
    for (final query in route.query) {
      buffer.writeln(
          "      $query: ZfaRouteParams.stringParam(queryParameters, "
          "'$query'),");
    }
    buffer.writeln('      pathParameters: pathParameters,');
    buffer.writeln('      queryParameters: queryParameters,');
    buffer.writeln('    );');
    buffer.writeln('  }');

    buffer.writeln();
    for (final param in pathParams) {
      final type = route.params[param] ?? 'String';
      buffer.writeln('  final $type $param;');
    }
    for (final query in route.query) {
      buffer.writeln('  final String? $query;');
    }
    buffer.writeln('}');
    buffer.writeln();
    return buffer.toString();
  }


  // ------------------------------------------------------------------
  // Deep-link artifacts (US-6)
  // ------------------------------------------------------------------

  static Map<String, String> _deepLinkFiles(List<RouteDeclaration> routes) {
    final deepLinkPaths = routes
        .where((r) => r.deepLinkAware)
        .map((r) => r.path)
        .toList()
      ..sort();

    if (deepLinkPaths.isEmpty) return const {};

    // Convert :params to wildcards for pattern matching.
    final patterns = deepLinkPaths
        .map((path) => path
            .split('/')
            .map((s) => s.startsWith(':') ? '*' : s)
            .join('/'))
        .map((pattern) => "'$pattern'")
        .toList();

    final apple = '''
{
  "applinks": {
    "apps": [],
    "details": [
      {
        "paths": [
          ${patterns.join(',\n          ')}
        ]
      }
    ]
  }
}
''';

    final android = '''
[
  {
    "relation": [
      "delegate_permission/common.handle_all_urls"
    ],
    "target": {},
    "paths": [
      ${patterns.join(',\n      ')}
    ]
  }
]
''';

    return {
      '.well-known/apple-app-site-association': apple,
      '.well-known/assetlinks.json': android,
    };
  }
}
