import 'package:code_builder/code_builder.dart';
import 'package:dart_style/dart_style.dart';

/// Emits the runtime MCP server files scaffolded by `zfa plugin mcp`.
///
/// Two concerns:
///
///  1. [buildToolsFile] — `lib/src/mcp/tools.dart`. Declares the
///     app's [McpTool] list. Initially populated with a placeholder
///     `EchoTool` so the file compiles and the scaffolded server
///     is immediately runnable. Developers replace it with their
///     real tools.
///
///  2. [buildBinServer] — `bin/mcp_server.dart`. Standalone
///     entrypoint that boots a `ZuraffaEngine` + `McpServerPlugin`
///     and serves stdio (default) or SSE (`--sse`). Supports
///     `--list-tools` for `zfa mcp list-tools`.
///
/// All emitted files are stamped `// Generated by zfa` (NOT wrapped
/// in `// GENERATED - DO NOT EDIT` markers — those are reserved for
/// build_runner outputs, per the convention established by
/// `AppShellBuilder`).
class McpScaffoldBuilder {
  static const String generatedStamp = '// Generated by zfa';

  /// Builds `lib/src/mcp/tools.dart`.
  ///
  /// [appName] is the Dart package name from `pubspec.yaml`, used
  /// only in a comment. The file itself imports
  /// `package:zuraffa/zuraffa.dart`.
  String buildToolsFile({String? appName}) {
    final emitter = DartFormatter(
      languageVersion: DartFormatter.latestLanguageVersion,
    );

    final library = Library(
      (b) => b
        ..directives.add(Directive.import('package:zuraffa/zuraffa.dart'))
        ..body.add(
          Class(
            (c) => c
              ..name = 'EchoTool'
              ..docs.addAll([
                '/// Placeholder MCP tool. Replace with your real tools.',
                '///',
                '/// Each [McpTool] you declare here is exposed by the',
                '/// scaffolded MCP server (`zfa mcp serve`) and callable',
                '/// by AI agents via JSON-RPC.',
              ])
              ..implements.add(refer('McpTool'))
              ..methods.addAll([
                Method(
                  (m) => m
                    ..annotations.add(refer('override'))
                    ..name = 'name'
                    ..type = MethodType.getter
                    ..returns = refer('String')
                    ..body = const Code("return 'echo';"),
                ),
                Method(
                  (m) => m
                    ..annotations.add(refer('override'))
                    ..name = 'description'
                    ..type = MethodType.getter
                    ..returns = refer('String')
                    ..body = const Code(
                      "return 'Echoes back the message argument. "
                      "Replace this tool with your real app features.';",
                    ),
                ),
                Method(
                  (m) => m
                    ..annotations.add(refer('override'))
                    ..name = 'inputSchema'
                    ..type = MethodType.getter
                    ..returns = refer('Map<String, dynamic>')
                    ..body = Code(
                      "return const {\n"
                      "  'type': 'object',\n"
                      "  'properties': {\n"
                      "    'message': {\n"
                      "      'type': 'string',\n"
                      "      'description': 'The message to echo back.',\n"
                      "    },\n"
                      "  },\n"
                      "  'required': ['message'],\n"
                      "};",
                    ),
                ),
                Method(
                  (m) => m
                    ..annotations.add(refer('override'))
                    ..name = 'call'
                    ..returns = refer('Future<McpToolResult>')
                    ..requiredParameters.add(
                      Parameter(
                        (p) => p
                          ..name = 'arguments'
                          ..type = refer('Map<String, dynamic>'),
                      ),
                    )
                    ..modifier = MethodModifier.async
                    ..body = const Code(
                      "final message = arguments['message'] as String? ?? '';\n"
                      "return McpToolResult.ok('echo: \$message');",
                    ),
                ),
              ]),
          ),
        )
        ..body.add(
          Method(
            (m) => m
              ..docs.addAll([
                '/// The list of MCP tools this app exposes.',
                '///',
                '/// Add your tool instances here. The scaffolded MCP',
                '/// server (bin/mcp_server.dart) reads this list at',
                '/// startup and registers every tool with the engine\'s',
                '/// McpToolRegistry.',
              ])
              ..name = 'mcpTools'
              ..type = MethodType.getter
              ..returns = refer('List<McpTool>')
              ..body = const Code('return [\n  EchoTool(),\n];'),
          ),
        ),
    );

    final raw = library.accept(DartEmitter()).toString();
    // Mirror buildBinServer's formatter-error behavior: fall back to
    // the unformatted raw source if the emitter can't format it.
    late final String code;
    try {
      code = emitter.format(raw);
    } catch (_) {
      code = raw;
    }
    return '$generatedStamp\n// MCP tools for the ${appName ?? 'app'} package.\n$code';
  }

  /// Builds `bin/mcp_server.dart`.
  ///
  /// [appName] is the Dart package name from `pubspec.yaml`,
  /// used for the `package:<appName>/<rel>/mcp/tools.dart` import.
  /// [outputDir] is the project-root-relative output dir (default
  /// `lib/src`) — used to compute the package import path for the
  /// tools file.
  String buildBinServer({
    required String appName,
    String outputDir = 'lib/src',
  }) {
    final toolsImport = _packageImport(appName, outputDir, 'mcp/tools.dart');

    final buf = StringBuffer()
      ..writeln(generatedStamp)
      ..writeln('// Standalone MCP server entrypoint for the $appName package.')
      ..writeln('//')
      ..writeln('// Run via:')
      ..writeln(
        '//   dart run bin/mcp_server.dart            # stdio (default)',
      )
      ..writeln('//   dart run bin/mcp_server.dart --sse      # SSE on :8372')
      ..writeln('//   dart run bin/mcp_server.dart --list-tools')
      ..writeln('library;')
      ..writeln()
      ..writeln("import 'dart:convert';")
      ..writeln("import 'dart:io';")
      ..writeln("import 'package:zuraffa/zuraffa.dart';")
      ..writeln("import '$toolsImport';")
      ..writeln()
      ..writeln('Future<void> main(List<String> args) async {')
      ..writeln('  final useSse = args.contains(\'--sse\');')
      ..writeln('  final listToolsOnly = args.contains(\'--list-tools\');')
      ..writeln('  final ssePort = _intArg(args, \'--port\', 8372);')
      ..writeln('  final authToken = _strArg(args, \'--token\');')
      ..writeln()
      ..writeln('  final mcp = McpServerPlugin(tools: mcpTools);')
      ..writeln('  final engine = ZuraffaEngine()..register(mcp);')
      ..writeln('  await engine.bootstrap();')
      ..writeln()
      ..writeln('  if (listToolsOnly) {')
      ..writeln('    final tools = mcp.listTools().map((t) => {')
      ..writeln('      \'name\': t.name,')
      ..writeln('      \'description\': t.description,')
      ..writeln('      \'inputSchema\': t.inputSchema,')
      ..writeln('    }).toList();')
      ..writeln('    print(jsonEncode({\'tools\': tools}));')
      ..writeln('    return;')
      ..writeln('  }')
      ..writeln()
      ..writeln('  if (useSse) {')
      ..writeln('    await mcp.serveSse(port: ssePort, authToken: authToken);')
      ..writeln('  } else {')
      ..writeln('    await mcp.serveStdio();')
      ..writeln('  }')
      ..writeln('}')
      ..writeln()
      ..writeln(
        'int _intArg(List<String> args, String name, int defaultValue) {',
      )
      ..writeln('  final i = args.indexOf(name);')
      ..writeln('  if (i == -1 || i + 1 >= args.length) return defaultValue;')
      ..writeln('  return int.tryParse(args[i + 1]) ?? defaultValue;')
      ..writeln('}')
      ..writeln()
      ..writeln('String? _strArg(List<String> args, String name) {')
      ..writeln('  final i = args.indexOf(name);')
      ..writeln('  if (i == -1 || i + 1 >= args.length) return null;')
      ..writeln('  return args[i + 1];')
      ..writeln('}');

    // Format the file so subsequent edits see clean Dart.
    try {
      return DartFormatter(
        languageVersion: DartFormatter.latestLanguageVersion,
      ).format(buf.toString());
    } catch (_) {
      // Unparseable (rare — would indicate a builder bug). Return raw
      // so the user can see and report the broken output.
      return buf.toString();
    }
  }

  /// Returns the `package:` import path for a file under [outputDir].
  ///
  /// For `lib/src` → `package:<app>/src/<relative>`; for `lib` →
  /// `package:<app>/<relative>`. [relative] is the path *within*
  /// the output dir (e.g. `'mcp/tools.dart'`). A trailing slash on
  /// [outputDir] (e.g. `lib/src/`) is stripped first so the joined
  /// path never contains a double separator.
  String _packageImport(String app, String outputDir, String relative) {
    // Package names in pubspec.yaml may contain hyphens, but `package:`
    // URIs require underscores — normalize so hyphenated app names
    // scaffold into compilable imports.
    final normalizedApp = app.replaceAll('-', '_');
    final clean = outputDir.endsWith('/')
        ? outputDir.substring(0, outputDir.length - 1)
        : outputDir;
    final base = clean == 'lib' ? '' : clean.replaceFirst('lib/', '');
    final path = base.isEmpty ? relative : '$base/$relative';
    return 'package:$normalizedApp/$path';
  }
}
