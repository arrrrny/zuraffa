/// Generates repository interfaces for the domain layer.
///
/// Builds abstract repository classes with method definitions derived from
/// use cases and data requirements.
class RepositoryInterfaceGenerator {
  final String outputDir;
  final GeneratorOptions options;
  final AppendExecutor appendExecutor;
  final SpecLibrary specLibrary;
  final DiscoveryEngine discovery;
  final FileSystem fileSystem;

  RepositoryInterfaceGenerator({
    required this.outputDir,
    this.options = const GeneratorOptions(),
    this.appendExecutor = const AppendExecutor(),
    this.specLibrary = const SpecLibrary(),
    DiscoveryEngine? discovery,
    FileSystem? fileSystem,
  }) : fileSystem = fileSystem ?? FileSystem.create(),
       discovery =
           discovery ??
           DiscoveryEngine(
             projectRoot: outputDir,
             fileSystem: fileSystem ?? FileSystem.create(),
           );

  Future<GeneratedFile> generate(GeneratorConfig config) async {
    final repoName = '${config.name}Repository';
    final fileName = '${config.nameSnake}_repository.dart';
    final filePath = path.join(outputDir, 'domain', 'repositories', fileName);

    final methods = _buildMethods(config);
    final directives = _buildDirectives(config);
    final clazz = Class(
      (b) => b
        ..name = repoName
        ..abstract = true
        ..methods.addAll(methods),
    );

    final output = specLibrary.emitLibrary(
      specLibrary.library(specs: [clazz], directives: directives),
      leadingComment:
          '// Generated by zfa for: ${config.name}\n// zfa make ${config.name} --methods=${config.methods.join(',')} --repository',
    );

    if (await fileSystem.exists(filePath) &&
        (config.appendToExisting || !config.force)) {
      if (config.revert) {
        if (!config.appendToExisting) {
          return FileUtils.deleteFile(
            filePath,
            'repository',
            dryRun: options.dryRun,
            verbose: options.verbose,
            fileSystem: fileSystem,
          );
        }

        var source = await fileSystem.read(filePath);
        final emitter = DartEmitter(useNullSafetySyntax: true);

        for (final method in methods) {
          final methodSource = method.accept(emitter).toString();
          final request = AppendRequest.method(
            source: source,
            className: repoName,
            memberSource: methodSource,
          );
          source = appendExecutor.undo(request).source;
        }

        if (const AstHelper().isClassEmpty(source, repoName)) {
          return FileUtils.deleteFile(
            filePath,
            'repository',
            dryRun: options.dryRun,
            verbose: options.verbose,
            fileSystem: fileSystem,
          );
        }

        return FileUtils.writeFile(
          filePath,
          source,
          'repository',
          force: true,
          dryRun: options.dryRun,
          verbose: options.verbose,
          revert: false,
          fileSystem: fileSystem,
        );
      }

      if (config.appendToExisting) {
        var source = await fileSystem.read(filePath);
        final emitter = DartEmitter(useNullSafetySyntax: true);

        // 1. Add missing imports to host file
        for (final directive in directives) {
          source = const AstHelper().addImport(
            source: source,
            importPath: directive.url,
          );
        }

        // 2. Add methods directly to host file
        for (final method in methods) {
          final methodSource = method.accept(emitter).toString();
          final request = AppendRequest.method(
            source: source,
            className: repoName,
            memberSource: methodSource,
          );
          source = appendExecutor.execute(request).source;
        }

        await FileUtils.writeFile(
          filePath,
          source,
          'repository',
          force: true,
          dryRun: options.dryRun,
          verbose: options.verbose,
          fileSystem: fileSystem,
        );

        return GeneratedFile(
          path: filePath,
          type: 'repository',
          action: 'updated',
        );
      }

      return GeneratedFile(
        path: filePath,
        type: 'repository',
        action: 'skipped',
      );
    }

    if (config.revert) {
      return FileUtils.deleteFile(
        filePath,
        'repository',
        dryRun: options.dryRun,
        verbose: options.verbose,
        fileSystem: fileSystem,
      );
    }

    return FileUtils.writeFile(
      filePath,
      output,
      'repository',
      force: options.force,
      dryRun: options.dryRun,
      verbose: options.verbose,
      revert: false,
      fileSystem: fileSystem,
    );
  }

  List<Directive> _buildDirectives(GeneratorConfig config) {
    final needsZuraffaImport =
        config.methods.any(
          (method) =>
              method == 'get' ||
              method == 'watch' ||
              method == 'getList' ||
              method == 'update' ||
              method == 'delete' ||
              method == 'watchList',
        ) ||
        config.generateInit ||
        // FR-007: sync-enabled interfaces declare `syncPending`/`pullRemote`,
        // which reference `CancelToken` from zuraffa.
        config.enableSync;

    final imports = <String>[];
    if (needsZuraffaImport) {
      imports.add('package:zuraffa/zuraffa.dart');
    }
    var entityFileImported = false;
    if (config.isEntityBased) {
      final entityName = config.name;
      final entitySnake = config.nameSnake;

      final isEnum = EntityAnalyzer.isEnum(
        entityName,
        outputDir,
        fileSystem: fileSystem,
      );

      if (isEnum) {
        imports.add('../../domain/entities/enums/index.dart');
      } else {
        final entityFile = discovery.findFileSync('$entitySnake.dart');
        if (entityFile != null) {
          final repoDir = path.dirname(
            path.join(
              outputDir,
              'domain',
              'repositories',
              '${config.nameSnake}_repository.dart',
            ),
          );
          final relativePath = path.relative(entityFile.path, from: repoDir);
          imports.add(relativePath);
          entityFileImported = true;
        } else if (fileSystem.existsSync(
          path.join(
            outputDir,
            'domain',
            'entities',
            entitySnake,
            '$entitySnake.dart',
          ),
        )) {
          // Only reference the entity file when it actually exists — skip the
          // import for non-existent entities (e.g. an `Enums` entity that was
          // never created) so generation does not emit dangling URIs.
          imports.add('../../domain/entities/$entitySnake/$entitySnake.dart');
          entityFileImported = true;
        }
      }
    }

    // Resolve entity imports for custom params/returns types
    if (config.paramsType != null || config.returnsType != null) {
      imports.addAll(
        CommonPatterns.entityImports(
          [config.paramsType, config.returnsType],
          config,
          depth: 2,
          discovery: discovery,
          fileSystem: fileSystem,
        ),
      );
    }

    // Issue #942: the interface imports the entity file AND the framework
    // barrel unprefixed — an entity whose name matches a zuraffa core
    // export (e.g. `Credentials`) makes this file fail with
    // `ambiguous_import` errors. The generator knows the locally-imported
    // entity symbols (the entity file plus the custom params/returns
    // types), so the barrel import hides exactly those symbols and the
    // entity's own definitions win resolution. With no locally-imported
    // entity types the hide list stays empty and the import is emitted
    // unchanged.
    final barrelHide = <String>{
      if (entityFileImported) ...EntityUtils.barrelHideNames(config.name),
      ...CommonPatterns.barrelHideNamesForTypes([
        config.paramsType,
        config.returnsType,
      ]),
    }.toList();

    return imports.toSet().map((uri) {
      if (uri != 'package:zuraffa/zuraffa.dart' || barrelHide.isEmpty) {
        return Directive.import(uri);
      }
      return Directive.import(uri, hide: barrelHide);
    }).toList();
  }

  List<Method> _buildMethods(GeneratorConfig config) {
    final methods = <Method>[];

    if (config.isCustomUseCase && config.appendToExisting) {
      final methodName = config.getRepoMethodName();
      var returnType = config.returnsType ?? 'void';
      final paramsType = config.paramsType ?? 'NoParams';

      // Wrap in Future/Stream if not already
      if (config.useCaseType == 'stream' ||
          config.useCaseType == 'streamusecase') {
        if (!returnType.startsWith('Stream<')) {
          returnType = 'Stream<$returnType>';
        }
      } else if (config.useCaseType != 'sync' &&
          config.useCaseType != 'syncusecase') {
        if (!returnType.startsWith('Future<')) {
          returnType = 'Future<$returnType>';
        }
      }

      methods.add(
        _buildMethod(
          name: methodName,
          returnType: returnType,
          paramsType: paramsType,
          paramsName: 'params',
        ),
      );
    }

    if (config.generateInit) {
      methods.add(
        Method(
          (b) => b
            ..name = 'isInitialized'
            ..type = MethodType.getter
            ..returns = refer('Stream<bool>'),
        ),
      );
      methods.add(
        Method(
          (b) => b
            ..name = 'initialize'
            ..returns = refer('Future<void>')
            ..requiredParameters.add(
              Parameter(
                (p) => p
                  ..name = 'params'
                  ..type = refer('InitializationParams'),
              ),
            ),
        ),
      );
      methods.add(
        Method(
          (b) => b
            ..name = 'dispose'
            ..returns = refer('Future<void>'),
        ),
      );
    }

    for (final method in config.methods) {
      switch (method) {
        case 'get':
          methods.add(
            _buildMethod(
              name: 'get',
              returnType: 'Future<${config.name}>',
              paramsType: 'QueryParams<${config.name}>',
              paramsName: 'params',
            ),
          );
          break;
        case 'getList':
          methods.add(
            _buildMethod(
              name: 'getList',
              returnType: 'Future<List<${config.name}>>',
              paramsType: 'ListQueryParams<${config.name}>',
              paramsName: 'params',
            ),
          );
          break;
        // #406: `list` is a documented --methods value
        // (get,create,update,delete,list,watch,getList,watchList) but was
        // silently dropped from the interface — the implementation
        // generator's default branch still emitted `list(NoParams)` with
        // `@override`, producing override_on_non_overriding_member.
        case 'list':
          methods.add(
            _buildMethod(
              name: 'list',
              returnType: 'Future<List<${config.name}>>',
              paramsType: 'NoParams',
              paramsName: 'params',
            ),
          );
          break;
        case 'create':
          methods.add(
            _buildMethod(
              name: 'create',
              returnType: 'Future<${config.name}>',
              paramsType: config.name,
              paramsName: config.nameCamel,
            ),
          );
          break;
        case 'update':
          final dataType = config.useZorphy
              ? '${config.name}Patch'
              : 'Partial<${config.name}>';
          methods.add(
            _buildMethod(
              name: 'update',
              returnType: 'Future<${config.name}>',
              paramsType: 'UpdateParams<${config.idFieldType}, $dataType>',
              paramsName: 'params',
            ),
          );
          break;
        case 'toggle':
          final fieldEnum = 'Field<${config.name}, dynamic>';
          methods.add(
            _buildMethod(
              name: 'toggle',
              returnType: 'Future<${config.name}>',
              paramsType: 'ToggleParams<${config.idFieldType}, $fieldEnum>',
              paramsName: 'params',
            ),
          );
          break;
        case 'delete':
          methods.add(
            _buildMethod(
              name: 'delete',
              returnType: 'Future<void>',
              paramsType: 'DeleteParams<${config.idFieldType}>',
              paramsName: 'params',
            ),
          );
          break;
        case 'watch':
          methods.add(
            _buildMethod(
              name: 'watch',
              returnType: 'Stream<${config.name}>',
              paramsType: 'QueryParams<${config.name}>',
              paramsName: 'params',
            ),
          );
          break;
        case 'watchList':
          methods.add(
            _buildMethod(
              name: 'watchList',
              returnType: 'Stream<List<${config.name}>>',
              paramsType: 'ListQueryParams<${config.name}>',
              paramsName: 'params',
            ),
          );
          break;
      }
    }

    // FR-007: a sync-enabled repository must expose sync operations so the
    // generated `Sync<Entity>UseCase` can manually trigger a sync. The
    // signature mirrors the concrete synced repository (`{CancelToken?
    // cancelToken}`), so the implementing class satisfies the contract.
    if (config.enableSync) {
      methods.add(_buildSyncMethod('syncPending'));
      methods.add(_buildSyncMethod('pullRemote'));
    }

    return methods;
  }

  Method _buildMethod({
    required String name,
    required String returnType,
    required String paramsType,
    required String paramsName,
  }) {
    return Method(
      (b) => b
        ..name = name
        ..returns = refer(returnType)
        ..requiredParameters.add(
          Parameter(
            (p) => p
              ..name = paramsName
              ..type = refer(paramsType),
          ),
        ),
    );
  }

  /// Builds a sync-operation declaration (`syncPending` / `pullRemote`) for the
  /// sync-enabled repository interface. The signature matches the concrete
  /// synced repository: `Future<void> name({CancelToken? cancelToken});`.
  Method _buildSyncMethod(String name) {
    return Method(
      (b) => b
        ..name = name
        ..returns = refer('Future<void>')
        ..optionalParameters.add(
          Parameter(
            (p) => p
              ..name = 'cancelToken'
              ..type = TypeReference(
                (t) => t
                  ..symbol = 'CancelToken'
                  ..isNullable = true,
              )
              ..named = true,
          ),
        ),
    );
  }
}
