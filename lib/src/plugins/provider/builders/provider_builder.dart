/// Generates provider implementation classes.
///
/// Builds Dart classes that implement domain service interfaces, handling
/// data mapping and error handling.
///
/// Spec #979 (order 1): every emitted file carries the standard
/// `// GENERATED by zfa provider` provenance header, so `zfa proof check`
/// and humans can distinguish generated providers from hand-written ones.
/// The append/inject paths preserve the header via the AST engine (they
/// never rewrite the leading comment block).
class ProviderBuilder {
  /// The provenance header stamped on every freshly emitted provider file
  /// (issue #979 order 1 — GENERATED marker).
  static const String generatedHeader =
      '// GENERATED by zfa provider — DO NOT EDIT BY HAND.';

  /// The full header block (marker + regeneration hint) for [entityName].
  static String headerFor(String entityName) =>
      '$generatedHeader\n'
      '// Regenerate with: zfa provider create --name $entityName '
      '(--force to overwrite)\n\n';

  final String outputDir;
  final GeneratorOptions options;
  final SpecLibrary specLibrary;
  final DartEmitter emitter;
  final FileSystem fileSystem;

  ProviderBuilder({
    required this.outputDir,
    this.options = const GeneratorOptions(),
    SpecLibrary? specLibrary,
    DartEmitter? emitter,
    FileSystem? fileSystem,
  }) : specLibrary = specLibrary ?? const SpecLibrary(),
       emitter =
           emitter ??
           DartEmitter(orderDirectives: true, useNullSafetySyntax: true),
       fileSystem = fileSystem ?? FileSystem.create();

  Future<GeneratedFile> generate(GeneratorConfig config) async {
    final serviceName = config.effectiveService;
    final providerName = config.effectiveProvider;
    final providerSnake = config.providerSnake;
    final serviceSnake = config.serviceSnake;
    if (serviceName == null ||
        providerName == null ||
        providerSnake == null ||
        serviceSnake == null) {
      throw ArgumentError(
        'Service name must be specified via --service or config.service',
      );
    }

    final fileName = '${providerSnake}_provider.dart';
    var filePath = path.join(
      outputDir,
      'data',
      'providers',
      config.effectiveDomain,
      fileName,
    );

    // Check if provider already exists in any folder under providers/
    final existingFile = await FileUtils.findFileImplementing(
      path.join(outputDir, 'data', 'providers'),
      serviceName,
      fileSystem: fileSystem,
    );

    final fileExists =
        existingFile != null || await fileSystem.exists(filePath);
    if (existingFile != null) {
      filePath = existingFile;
    }

    if (config.revert && !config.appendToExisting) {
      // Issue #1719 review: the per-invocation flags live on the config.
      // This read used the plugin-level const [options] (always false), so
      // `zfa provider create --revert --dry-run` — and a plan() run with
      // revert: true, which hardcodes dryRun — DELETED the provider for
      // real instead of previewing the deletion.
      return FileUtils.deleteFile(
        filePath,
        'provider',
        dryRun: config.dryRun,
        verbose: config.verbose,
        fileSystem: fileSystem,
      );
    }

    final paramsType = config.paramsType ?? 'NoParams';
    final returnsType = config.returnsType ?? 'void';
    final methodName = config.getServiceMethodName();

    final returnType = _returnType(config.useCaseType, returnsType);

    final serviceImport = config.isEntityBased
        ? '../../../domain/services/${config.effectiveDomain}/${serviceSnake}_service.dart'
        : '../../../domain/services/${serviceSnake}_service.dart';

    final entityTypes = <String>{};
    if (config.isEntityBased) {
      entityTypes.add(config.name);
    }
    entityTypes.addAll(_getPotentialEntityImports([paramsType, returnsType]));

    final methods = <Method>[];

    // Issue #1719: the --init members are emitted EXACTLY ONCE, with their
    // semantic bodies (empty init stream / async no-ops). When the service
    // interface already declares them (an --init service), the interface
    // extraction below skips those names — emitting them twice produced
    // duplicate_definition compile errors (getter vs method isInitialized,
    // initialize twice, dispose with mismatched signatures).
    final initMembers = config.generateInit
        ? _buildInitMembers()
        : const <Method>[];
    final initMemberNames = initMembers.map((m) => m.name!).toSet();

    // Check for existing service methods
    final servicePath = config.isEntityBased
        ? path.join(
            outputDir,
            'domain',
            'services',
            config.effectiveDomain,
            '${serviceSnake}_service.dart',
          )
        : path.join(
            outputDir,
            'domain',
            'services',
            '${serviceSnake}_service.dart',
          );

    final existingMethods = await MethodExtractor.extractMethodsFromInterface(
      servicePath,
      serviceName,
      fileSystem: fileSystem,
    );

    if (config.methods.isNotEmpty) {
      for (final method in config.methods) {
        methods.add(_buildEntityMethod(config, method));
      }
    } else if (existingMethods.isNotEmpty) {
      for (final info in existingMethods) {
        // Issue #1719: one implementation member per interface member. The
        // --init members are emitted once (above/below) with their semantic
        // bodies; the interface-extracted copies are skipped here — but
        // only when the interface member's SIGNATURE matches the canonical
        // init shape (issue #1719 review: dedup by name alone silently
        // replaced a hand-modified member with the canonical stub,
        // producing a provider that no longer implements its interface).
        if (initMemberNames.contains(info.fieldName)) {
          if (_matchesCanonicalInitShape(info)) {
            continue;
          }
          // The interface's own shape deviates from the canonical stub —
          // the interface wins. Drop the canonical member so the file
          // still carries exactly one member with this name, then emit
          // the interface's shape below.
          initMembers.removeWhere((m) => m.name == info.fieldName);
        }

        final returns = info.returnsType ?? 'void';
        final params = info.paramsType ?? 'NoParams';

        methods.add(_buildImplementationMember(info));

        // Collect potential entity imports for existing methods
        entityTypes.addAll(_getPotentialEntityImports([params, returns]));
      }
    } else if (config.paramsType != null || config.returnsType != null) {
      methods.add(
        Method(
          (m) => m
            ..name = methodName
            ..returns = returnType
            ..annotations.add(refer('override'))
            ..modifier =
                (config.useCaseType == 'sync' || config.useCaseType == 'stream')
                ? null
                : MethodModifier.async
            ..requiredParameters.addAll([
              Parameter(
                (p) => p
                  ..name = 'params'
                  ..type = refer(paramsType),
              ),
            ])
            ..body = _buildMethodBody(methodName),
        ),
      );
    }

    final entityImports = CommonPatterns.entityImports(
      entityTypes.toList(),
      config,
      // Providers live at lib/src/data/providers/<domain>/, so entity imports
      // need ../../../ (depth 3) to reach lib/src/domain/entities/... — matching
      // the service import depth emitted above for the same file. depth: 2
      // produced ../../ which is one level too shallow (issue #395 Bug A).
      depth: 3,
      includeDomain: false,
      fileSystem: fileSystem,
    );
    // Issue #942: the provider imports the entity file(s) AND the
    // framework barrel unprefixed — an entity whose name matches a
    // zuraffa core export (e.g. `Credentials`) makes this file fail with
    // `ambiguous_import` errors. The generator knows the locally-imported
    // entity symbols (`entityTypes` drives the entity imports below), so
    // the barrel import hides exactly those symbols and the entity's own
    // definitions win resolution. With no locally-imported entity types
    // the hide list stays empty and the import is emitted unchanged.
    final barrelHide = CommonPatterns.barrelHideNamesForTypes(entityTypes);

    final directives = <Directive>[
      if (barrelHide.isEmpty)
        Directive.import('package:zuraffa/zuraffa.dart')
      else
        Directive.import('package:zuraffa/zuraffa.dart', hide: barrelHide),
      Directive.import(serviceImport),
      ...entityImports.map(Directive.import),
    ];

    // Issue #1719: the init members were built once up front (alongside
    // initMemberNames, so the interface extraction could skip duplicates);
    // append them here in the canonical order.
    methods.addAll(initMembers);

    final providerClass = Class(
      (c) => c
        ..name = providerName
        ..mixins.addAll([refer('Loggable'), refer('FailureHandler')])
        ..implements.add(refer(serviceName))
        ..methods.addAll(methods),
    );

    if (config.appendToExisting && fileExists) {
      var content = await fileSystem.read(filePath);
      final helper = const AstHelper();

      // Add imports if missing
      for (final directive in directives) {
        final importLine = specLibrary.emitLibrary(
          specLibrary.library(specs: [], directives: [directive]),
        );
        if (!content.contains(importLine.trim()) || config.force) {
          if (!content.contains(importLine.trim())) {
            // Spec #979 (order 1): never let a prepended import displace
            // the GENERATED provenance header from the top of the file —
            // insert the import BELOW the leading comment block instead.
            content = _insertImportBelowHeader(content, importLine.trim());
          }
        }
      }

      for (final method in methods) {
        final methodSource = method.accept(emitter).toString();
        if (config.revert) {
          content = helper.removeMethodFromClass(
            source: content,
            className: providerName,
            methodName: method.name!,
          );
        } else if (config.force) {
          // Check if method exists to decide between replace and add
          if (content.contains(' ${method.name}(')) {
            content = helper.replaceMethodInClass(
              source: content,
              className: providerName,
              methodName: method.name!,
              methodSource: methodSource,
            );
          } else {
            content = helper.addMethodToClass(
              source: content,
              className: providerName,
              methodSource: methodSource,
            );
          }
        } else {
          // Add method to class if missing
          if (!content.contains(' ${method.name}(')) {
            content = helper.addMethodToClass(
              source: content,
              className: providerName,
              methodSource: methodSource,
            );
          }
        }
      }

      return FileUtils.writeFile(
        filePath,
        content,
        'provider',
        force: true,
        // Issue #1719 review: same options-vs-config root cause as the
        // delete path — the append write read the const plugin options, so
        // an append-mode `--dry-run` actually wrote the file.
        dryRun: config.dryRun,
        verbose: config.verbose,
        revert: config.revert,
        fileSystem: fileSystem,
      );
    }

    final content = specLibrary.emitLibrary(
      specLibrary.library(specs: [providerClass], directives: directives),
    );

    // Spec #979 (order 1): the GENERATED provenance header rides ABOVE the
    // emitted library (before the imports); dart_style keeps it in place
    // through FileUtils.writeFile's format pass.
    final withHeader = '${headerFor(config.name)}$content';

    return FileUtils.writeFile(
      filePath,
      withHeader,
      'provider',
      // Issue #1719: the per-invocation flags live on the config — the
      // plugin-level [options] are the const defaults the CLI constructs
      // with, so `--force`/`--dry-run` used to be dropped on this write
      // (an existing file was "skipped" even WITH --force, and a --dry-run
      // plan actually wrote new files).
      force: config.force,
      dryRun: config.dryRun,
      verbose: config.verbose,
      revert: config.revert,
      fileSystem: fileSystem,
    );
  }

  /// Inserts [importLine] below the leading comment block of [content]
  /// when the file starts with the GENERATED provenance header (so the
  /// header stays the first thing in the file); otherwise prepends the
  /// import as before (issue #979 order 1).
  static String _insertImportBelowHeader(String content, String importLine) {
    if (!content.startsWith(generatedHeader)) {
      return '$importLine\n$content';
    }
    final lines = content.split('\n');
    var i = 0;
    while (i < lines.length &&
        (lines[i].startsWith('//') || lines[i].trim().isEmpty)) {
      i++;
    }
    final head = lines.take(i).join('\n');
    final tail = lines.skip(i).join('\n');
    return '$head\n$importLine\n$tail';
  }

  /// The `--init` implementation members, in canonical order: the
  /// `isInitialized` getter (empty stream), `initialize(InitializationParams)`
  /// and a parameter-less `dispose()`. Built once per generation so the
  /// interface extraction can skip signature-matching copies — exactly one
  /// implementation member per interface member (issue #1719). A member
  /// whose interface signature DEVIATES is emitted in the interface's own
  /// shape instead (see [_canonicalInitShapes]).
  static List<Method> _buildInitMembers() {
    return [
      Method(
        (m) => m
          ..name = 'isInitialized'
          ..returns = refer('Stream<bool>')
          ..type = MethodType.getter
          ..annotations.add(refer('override'))
          ..body = refer('const Stream.empty()').returned.statement,
      ),
      Method(
        (m) => m
          ..name = 'initialize'
          ..returns = refer('Future<void>')
          ..annotations.add(refer('override'))
          ..modifier = MethodModifier.async
          ..requiredParameters.add(
            Parameter(
              (p) => p
                ..name = 'params'
                ..type = refer('InitializationParams'),
            ),
          )
          ..body = Block((b) => b),
      ),
      Method(
        (m) => m
          ..name = 'dispose'
          ..returns = refer('Future<void>')
          ..annotations.add(refer('override'))
          ..modifier = MethodModifier.async
          ..body = Block((b) => b),
      ),
    ];
  }

  /// The canonical signature of each `--init` member, in the same terms
  /// interface extraction reports ([ParsedUseCaseInfo.isGetter],
  /// [ParsedUseCaseInfo.parameterCount], [ParsedUseCaseInfo.paramsType],
  /// [ParsedUseCaseInfo.useCaseType] and the CLEANED
  /// [ParsedUseCaseInfo.returnsType] — `Stream<bool>` → `bool`,
  /// `Future<void>` → `void`). Must stay in sync with [_buildInitMembers]:
  /// this table is the comparison key for the signature-aware dedup
  /// (issue #1719 review).
  static const Map<
    String,
    ({
      bool getter,
      int parameterCount,
      String paramType,
      String kind,
      String returns,
    })
  >
  _canonicalInitShapes = {
    'isInitialized': (
      getter: true,
      parameterCount: 0,
      paramType: '',
      kind: 'stream',
      returns: 'bool',
    ),
    'initialize': (
      getter: false,
      parameterCount: 1,
      paramType: 'InitializationParams',
      kind: 'completable',
      returns: 'void',
    ),
    'dispose': (
      getter: false,
      parameterCount: 0,
      paramType: '',
      kind: 'completable',
      returns: 'void',
    ),
  };

  /// True when [info] — a member extracted from the service interface —
  /// carries the exact canonical `--init` shape, so the canonical member
  /// (with its semantic body) can stand in for it. Any deviation (a
  /// hand-edited parameter type, a getter turned method, a different
  /// return type) is false and the interface's own shape is emitted.
  static bool _matchesCanonicalInitShape(ParsedUseCaseInfo info) {
    final shape = _canonicalInitShapes[info.fieldName];
    if (shape == null) return false;
    return info.isGetter == shape.getter &&
        info.parameterCount == shape.parameterCount &&
        (shape.parameterCount == 0 ||
            (info.paramsType ?? 'NoParams') == shape.paramType) &&
        (info.useCaseType ?? 'usecase') == shape.kind &&
        (info.returnsType ?? 'void') == shape.returns;
  }

  /// An implementation member for an interface member extracted from the
  /// service — emitted with the SAME SHAPE the interface declares
  /// (issue #1719): a getter stays a getter (no invented `params`
  /// parameter), a parameter-less method stays parameter-less, and a
  /// one-parameter method takes the interface's own parameter type.
  /// Emitting every member as `member(NoParams params)` both failed to
  /// implement the interface member and collided with the `--init`
  /// emission of the same names.
  Method _buildImplementationMember(ParsedUseCaseInfo info) {
    final returns = info.returnsType ?? 'void';
    final params = info.paramsType ?? 'NoParams';
    final type = info.useCaseType ?? 'usecase';

    if (info.isGetter) {
      return Method(
        (m) => m
          ..name = info.fieldName
          ..returns = _returnType(type, returns)
          ..type = MethodType.getter
          ..annotations.add(refer('override'))
          ..body = _buildMethodBody(info.fieldName),
      );
    }

    return Method(
      (m) => m
        ..name = info.fieldName
        ..returns = _returnType(type, returns)
        ..annotations.add(refer('override'))
        ..modifier = (type == 'sync' || type == 'stream')
            ? null
            : MethodModifier.async
        ..requiredParameters.addAll(
          info.parameterCount > 0
              ? [
                  Parameter(
                    (p) => p
                      ..name = 'params'
                      ..type = refer(params),
                  ),
                ]
              : const <Parameter>[],
        )
        ..body = _buildMethodBody(info.fieldName),
    );
  }

  Method _buildEntityMethod(GeneratorConfig config, String method) {
    final entityName = config.name;
    String name = method;
    Reference returnType;
    List<Parameter> parameters = [];

    switch (method) {
      case 'get':
        returnType = refer('Future<$entityName>');
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer('QueryParams<$entityName>'),
          ),
        );
        break;
      case 'getList':
      case 'list':
        name = 'getList';
        returnType = refer('Future<List<$entityName>>');
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer('ListQueryParams<$entityName>'),
          ),
        );
        break;
      case 'create':
        returnType = refer('Future<$entityName>');
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'item'
              ..type = refer(entityName),
          ),
        );
        break;
      case 'update':
        returnType = refer('Future<$entityName>');
        final providerDataType = config.useZorphy
            ? '${entityName}Patch'
            : 'Partial<$entityName>';
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer(
                'UpdateParams<${config.idFieldType}, $providerDataType>',
              ),
          ),
        );
        break;
      case 'delete':
        returnType = refer('Future<void>');
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer('DeleteParams<${config.idFieldType}>'),
          ),
        );
        break;
      // Issue #978 (make-triad consistency): `toggle` is part of the
      // entity-methods default (['get', 'update', 'toggle']) the service
      // interface builder mirrors — the provider implementation must carry
      // the same member or the #921 conformance guard fails the make run.
      // Signature mirrors the service builder's toggle case exactly.
      case 'toggle':
        returnType = refer('Future<$entityName>');
        final fieldEnum = 'Field<$entityName, dynamic>';
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer('ToggleParams<${config.idFieldType}, $fieldEnum>'),
          ),
        );
        break;
      case 'watch':
        returnType = refer('Stream<$entityName>');
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer('QueryParams<$entityName>'),
          ),
        );
        break;
      case 'watchList':
        returnType = refer('Stream<List<$entityName>>');
        parameters.add(
          Parameter(
            (p) => p
              ..name = 'params'
              ..type = refer('ListQueryParams<$entityName>'),
          ),
        );
        break;
      default:
        throw ArgumentError('Unknown entity method: $method');
    }

    return Method(
      (m) => m
        ..name = name
        ..returns = returnType
        ..annotations.add(refer('override'))
        ..modifier = method.startsWith('watch') ? null : MethodModifier.async
        ..requiredParameters.addAll(parameters)
        ..body = _buildMethodBody(name),
    );
  }

  Reference _returnType(String useCaseType, String returnsType) {
    switch (useCaseType) {
      case 'stream':
        return TypeReference(
          (b) => b
            ..symbol = 'Stream'
            ..types.add(refer(returnsType)),
        );
      case 'completable':
        return TypeReference(
          (b) => b
            ..symbol = 'Future'
            ..types.add(refer('void')),
        );
      case 'sync':
        return refer(returnsType);
      default:
        return TypeReference(
          (b) => b
            ..symbol = 'Future'
            ..types.add(refer(returnsType)),
        );
    }
  }

  Code _buildMethodBody(String methodName) {
    return Block(
      (b) => b
        ..statements.add(
          declareFinal('error')
              .assign(
                refer(
                  'UnimplementedError',
                ).call([literalString('$methodName not implemented')]),
              )
              .statement,
        )
        ..statements.add(
          declareFinal(
            'stack',
          ).assign(refer('StackTrace').property('current')).statement,
        )
        ..statements.add(
          refer(
            'logAndHandleError',
          ).call([refer('error'), refer('stack')]).statement,
        )
        ..statements.add(refer('error').thrown.statement),
    );
  }

  List<String> _getPotentialEntityImports(List<String> types) {
    final entities = <String>[];
    final primitives = {
      'void',
      'String',
      'int',
      'double',
      'bool',
      'dynamic',
      'Object',
      'NoParams',
      'Params',
      'QueryParams',
      'ListQueryParams',
      'UpdateParams',
      'DeleteParams',
      'CreateParams',
      'Map',
      'Set',
      'List',
      'Result',
      'AppFailure',
      'Duration',
      'DateTime',
    };

    for (final type in types) {
      final baseTypes = _extractBaseTypes(type);
      for (final baseType in baseTypes) {
        if (!primitives.contains(baseType) &&
            !baseType.startsWith('Map<') &&
            !baseType.startsWith('Set<')) {
          entities.add(baseType);
        }
      }
    }

    return entities.toSet().toList();
  }

  List<String> _extractBaseTypes(String type) {
    final cleanType = type.replaceAll('?', '');
    final results = <List<String>>[];

    final genericMatch = RegExp(r'(\w+)<(.+)>').firstMatch(cleanType);
    if (genericMatch != null) {
      final innerType = genericMatch.group(2);
      if (innerType != null) {
        results.add(_extractBaseTypes(innerType));
      }
    } else {
      if (cleanType.isNotEmpty && cleanType != 'void') {
        results.add([cleanType]);
      }
    }

    return results.expand((e) => e).toList();
  }
}
