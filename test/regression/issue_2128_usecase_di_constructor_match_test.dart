@Tags(['regression', 'slow'])
library;

// Regression test for issue #2128:
// https://github.com/arrrrny/zuraffa/issues/2128
//
// `zfa make ... --usecase --di` keeps a legacy use case it skips (the
// use-case generator reports `skipped` for an already-present file) but
// still OVERWRITES its DI file, and the DI template hard-codes the new
// service-delegating constructor shape:
//
//     RunPriceCheckForItemUseCase(getIt<RunPriceCheckForItemService>())
//
// When the retained legacy use case declares a NAMED constructor
// (`RunPriceCheckForItemUseCase({required GetUrlListingUseCase getUrlListing})`)
// the regenerated DI call is positional and cannot compile. The DI generator
// never inspects the use-case file it imports.
//
// The fix: when the imported use-case file already exists on disk, the DI
// generator parses its actual constructor and emits a matching call — named
// arguments for a named/optional constructor, positional otherwise. A freshly
// generated use case (constructor just written in the same run) keeps the
// existing positional emission.
//
// Fast tier: in-process plugin invocation into a throwaway directory; no
// subprocess, no pub get.

import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:zuraffa/src/core/generator_options.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/di/di_plugin.dart';

void main() {
  late Directory tempDir;
  late String outputDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('zfa_2128_');
    outputDir = p.join(tempDir.path, 'lib', 'src');
  });

  tearDown(() async {
    if (tempDir.existsSync()) {
      await tempDir.delete(recursive: true);
    }
  });

  // The issue's exact repro shape: a custom stream use case backed by a
  // service, generated with --no-entity (isCustomUseCase) and --di.
  GeneratorConfig runPriceCheckConfig(String dir) => GeneratorConfig(
    name: 'RunPriceCheckForItem',
    useCaseType: 'stream',
    domain: 'price_check',
    service: 'RunPriceCheckForItemService',
    paramsType: 'PriceCheckParams',
    returnsType: 'PriceCheckItemResult',
    outputDir: dir,
    noEntity: true,
    generateDi: true,
    generateUseCase: true,
  );

  group('issue #2128 — custom use case DI matches the actual constructor', () {
    test('fresh generation still emits the positional service call', () async {
      // No legacy use-case file on disk: DI generates against the use case
      // the same run would create — the positional form is correct here.
      final diFiles = await DiPlugin(
        outputDir: outputDir,
        options: const GeneratorOptions(dryRun: false, force: true),
      ).generate(runPriceCheckConfig(outputDir));

      final diFile = diFiles.firstWhere(
        (f) => f.path.endsWith(
          p.join('di', 'usecases', 'run_price_check_for_item_usecase_di.dart'),
        ),
        orElse: () => throw StateError(
          'DI file was not generated. Generated: ${diFiles.map((f) => f.path)}',
        ),
      );
      final content = diFile.content ?? '';
      expect(
        content,
        contains(
          'RunPriceCheckForItemUseCase(getIt<RunPriceCheckForItemService>())',
        ),
        reason:
            'a freshly generated use case keeps the positional service '
            'delegation the use-case generator writes',
      );
    });

    test(
      'a retained legacy NAMED-constructor use case gets named DI args',
      () async {
        // The legacy use case the use-case generator would SKIP: a named
        // constructor taking GetUrlListingUseCase.
        final usecaseDir = Directory(
          p.join(outputDir, 'domain', 'usecases', 'price_check'),
        );
        await usecaseDir.create(recursive: true);
        await File(
          p.join(usecaseDir.path, 'run_price_check_for_item_usecase.dart'),
        ).writeAsString(
          "import 'package:zuraffa/zuraffa.dart';\n"
          "import '../../usecases/get_url_listing/get_url_listing_usecase.dart';\n"
          '// Generated by zfa for: RunPriceCheckForItem\n'
          'class RunPriceCheckForItemUseCase '
          'extends StreamUseCase<PriceCheckItemResult, PriceCheckParams> {\n'
          '  final GetUrlListingUseCase _getUrlListing;\n'
          '\n'
          '  RunPriceCheckForItemUseCase({\n'
          '    required GetUrlListingUseCase getUrlListing,\n'
          '  }) : _getUrlListing = getUrlListing;\n'
          '\n'
          '  @override\n'
          '  Stream<PriceCheckItemResult> execute(\n'
          '    PriceCheckParams params, [\n'
          '    CancelToken? cancelToken,\n'
          '  ]) {\n'
          '    throw UnimplementedError();\n'
          '  }\n'
          '}\n',
        );

        // The dependency use case must also exist on disk so the DI
        // generator can resolve its import path (issue #2133 review: the
        // generated file references GetUrlListingUseCase and must import it).
        final depUsecaseDir = Directory(
          p.join(outputDir, 'domain', 'usecases', 'get_url_listing'),
        );
        await depUsecaseDir.create(recursive: true);
        await File(
          p.join(depUsecaseDir.path, 'get_url_listing_usecase.dart'),
        ).writeAsString(
          "import 'package:zuraffa/zuraffa.dart';\n"
          '// Generated by zfa for: GetUrlListing\n'
          'class GetUrlListingUseCase {\n'
          '  GetUrlListingUseCase();\n'
          '}\n',
        );

        final diFiles = await DiPlugin(
          outputDir: outputDir,
          options: const GeneratorOptions(dryRun: false, force: true),
        ).generate(runPriceCheckConfig(outputDir));

        final diFile = diFiles.firstWhere(
          (f) => f.path.endsWith(
            p.join(
              'di',
              'usecases',
              'run_price_check_for_item_usecase_di.dart',
            ),
          ),
          orElse: () => throw StateError(
            'DI file was not generated. Generated: ${diFiles.map((f) => f.path)}',
          ),
        );
        final content = diFile.content ?? '';

        // THE regression pin: the DI call must use a NAMED argument matching
        // the retained legacy constructor, not the positional service form.
        expect(
          content,
          isNot(contains('RunPriceCheckForItemUseCase(getIt<')),
          reason:
              'the positional service constructor call would not compile '
              'against the retained named-constructor use case',
        );
        expect(
          content,
          contains('getUrlListing:'),
          reason:
              'the DI call must pass the legacy constructor\'s required named '
              'parameter',
        );
        expect(
          content,
          contains('getIt<GetUrlListingUseCase>()'),
          reason:
              'the named argument must resolve the use case from the container',
        );
        // Issue #2133 review: the generated file must also IMPORT the
        // parameter type, not just reference it — otherwise it does not
        // compile.
        expect(
          content,
          contains('get_url_listing_usecase.dart'),
          reason:
              'the generated DI file must import GetUrlListingUseCase from '
              'its on-disk location; without it getIt<GetUrlListingUseCase>() '
              'references an unimported type and does not compile',
        );
      },
    );

    test(
      'a nullable constructor parameter uses a non-nullable getIt lookup',
      () async {
        // A retained use case whose constructor takes a nullable service:
        // GetIt 9.x declares call<T extends Object>, so getIt<AuthService?>()
        // does not compile. The lookup must strip outer nullability while the
        // constructor parameter type is left unchanged (issue #2133 review).
        final usecaseDir = Directory(
          p.join(outputDir, 'domain', 'usecases', 'price_check'),
        );
        await usecaseDir.create(recursive: true);
        await File(
          p.join(usecaseDir.path, 'run_price_check_for_item_usecase.dart'),
        ).writeAsString(
          "import 'package:zuraffa/zuraffa.dart';\n"
          "import '../../services/auth_service.dart';\n"
          '// Generated by zfa for: RunPriceCheckForItem\n'
          'class RunPriceCheckForItemUseCase '
          'extends StreamUseCase<PriceCheckItemResult, PriceCheckParams> {\n'
          '  final AuthService? _authService;\n'
          '\n'
          '  RunPriceCheckForItemUseCase({\n'
          '    required AuthService? authService,\n'
          '  }) : _authService = authService;\n'
          '\n'
          '  @override\n'
          '  Stream<PriceCheckItemResult> execute(\n'
          '    PriceCheckParams params, [\n'
          '    CancelToken? cancelToken,\n'
          '  ]) {\n'
          '    throw UnimplementedError();\n'
          '  }\n'
          '}\n',
        );

        final serviceDir = Directory(p.join(outputDir, 'domain', 'services'));
        await serviceDir.create(recursive: true);
        await File(p.join(serviceDir.path, 'auth_service.dart')).writeAsString(
          "abstract class AuthService {\n"
          '  Future<void> signIn();\n'
          '}\n',
        );

        final diFiles = await DiPlugin(
          outputDir: outputDir,
          options: const GeneratorOptions(dryRun: false, force: true),
        ).generate(runPriceCheckConfig(outputDir));

        final diFile = diFiles.firstWhere(
          (f) => f.path.endsWith(
            p.join(
              'di',
              'usecases',
              'run_price_check_for_item_usecase_di.dart',
            ),
          ),
          orElse: () => throw StateError(
            'DI file was not generated. Generated: ${diFiles.map((f) => f.path)}',
          ),
        );
        final content = diFile.content ?? '';

        // The lookup must use the non-nullable type — getIt<AuthService?>()
        // does not compile against GetIt 9.x.
        expect(
          content,
          isNot(contains('getIt<AuthService?>')),
          reason:
              'getIt<AuthService?>() does not compile — GetIt 9.x declares '
              'call<T extends Object>, so a nullable type argument is invalid',
        );
        expect(
          content,
          contains('getIt<AuthService>()'),
          reason:
              'the lookup type must strip outer nullability while the '
              'constructor parameter type is left unchanged in the use case',
        );
        expect(
          content,
          contains('auth_service.dart'),
          reason:
              'the generated DI file must import AuthService from its '
              'on-disk location',
        );
      },
    );

    test('an optional named parameter is skipped so its default applies', () async {
      // A retained use case with an optional named parameter:
      // emitting `cancelToken: getIt<CancelToken?>()` would override the
      // default with a nullable container lookup that is not registered
      // (issue #2133 review). The param must be skipped.
      final usecaseDir = Directory(
        p.join(outputDir, 'domain', 'usecases', 'price_check'),
      );
      await usecaseDir.create(recursive: true);
      await File(
        p.join(usecaseDir.path, 'run_price_check_for_item_usecase.dart'),
      ).writeAsString(
        "import 'package:zuraffa/zuraffa.dart';\n"
        "import '../../usecases/get_url_listing/get_url_listing_usecase.dart';\n"
        '// Generated by zfa for: RunPriceCheckForItem\n'
        'class RunPriceCheckForItemUseCase '
        'extends StreamUseCase<PriceCheckItemResult, PriceCheckParams> {\n'
        '  final GetUrlListingUseCase _getUrlListing;\n'
        '\n'
        '  RunPriceCheckForItemUseCase({\n'
        '    required GetUrlListingUseCase getUrlListing,\n'
        '    CancelToken? cancelToken,\n'
        '  }) : _getUrlListing = getUrlListing;\n'
        '\n'
        '  @override\n'
        '  Stream<PriceCheckItemResult> execute(\n'
        '    PriceCheckParams params, [\n'
        '    CancelToken? cancelToken,\n'
        '  ]) {\n'
        '    throw UnimplementedError();\n'
        '  }\n'
        '}\n',
      );

      final depUsecaseDir = Directory(
        p.join(outputDir, 'domain', 'usecases', 'get_url_listing'),
      );
      await depUsecaseDir.create(recursive: true);
      await File(
        p.join(depUsecaseDir.path, 'get_url_listing_usecase.dart'),
      ).writeAsString(
        "import 'package:zuraffa/zuraffa.dart';\n"
        'class GetUrlListingUseCase {\n'
        '  GetUrlListingUseCase();\n'
        '}\n',
      );

      final diFiles = await DiPlugin(
        outputDir: outputDir,
        options: const GeneratorOptions(dryRun: false, force: true),
      ).generate(runPriceCheckConfig(outputDir));

      final diFile = diFiles.firstWhere(
        (f) => f.path.endsWith(
          p.join('di', 'usecases', 'run_price_check_for_item_usecase_di.dart'),
        ),
        orElse: () => throw StateError(
          'DI file was not generated. Generated: ${diFiles.map((f) => f.path)}',
        ),
      );
      final content = diFile.content ?? '';

      // The required named param is emitted...
      expect(
        content,
        contains('getUrlListing:'),
        reason:
            'the required named parameter must still be passed to the '
            'constructor',
      );
      // ...but the optional named param is NOT force-resolved.
      expect(
        content,
        isNot(contains('cancelToken:')),
        reason:
            'an optional named parameter must be skipped so the '
            'constructor\'s own default applies; emitting '
            'cancelToken: getIt<CancelToken?>() would override the default '
            'with an unregistered nullable lookup',
      );
    });
  });
}
