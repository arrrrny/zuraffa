import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:zuraffa/src/core/generator_options.dart';
import 'package:zuraffa/src/core/proof/proof_checker.dart';
import 'package:zuraffa/src/plugins/provider/capabilities/create_provider_capability.dart';
import 'package:zuraffa/src/plugins/provider/provider_plugin.dart';
import 'package:zuraffa/src/plugins/provider/provider_receipt.dart';

/// Spec 979, order 1 — provenance for generated providers:
///
///   * every emitted provider file carries the standard
///     `// GENERATED by zfa provider` header;
///   * `zfa provider create` writes the deterministic receipt
///     `.zfa/receipts/provider-<Entity>.json` recording the interface, the
///     methods, and the stub count (plus the proof.v1 digests of the exact
///     bytes that landed on disk);
///   * `zfa proof check` is green on fresh generation and RED on hand-edit
///     (a tampered artifact no longer proves where it came from).
///
/// Fast tier: in-process capability execution in a temp project.
void main() {
  late Directory project;
  late String outputDir;
  late CreateProviderCapability capability;

  setUp(() async {
    project = await Directory.systemTemp.createTemp('zfa_provider_receipt_');
    outputDir = p.join(project.path, 'lib', 'src');
    final plugin = ProviderPlugin(
      outputDir: outputDir,
      options: const GeneratorOptions(force: true),
    );
    // Injectable project root: the CLI derives it from Directory.current;
    // tests must not mutate the process CWD (issue #441 race).
    capability = CreateProviderCapability(plugin, projectRoot: project.path);
  });

  tearDown(() async {
    if (project.existsSync()) {
      await project.delete(recursive: true);
    }
  });

  void writeServiceInterface(String entity) {
    final snake = entity.toLowerCase();
    final dir = p.join(outputDir, 'domain', 'services');
    Directory(dir).createSync(recursive: true);
    File(p.join(dir, '${snake}_service.dart')).writeAsStringSync('''
import 'package:zuraffa/zuraffa.dart';

abstract class ${entity}Service {
  Future<void> execute(NoParams params);
}
''');
  }

  test(
    'generated provider file carries the // GENERATED by zfa provider header',
    () async {
      writeServiceInterface('Cart');

      final result = await capability.execute({'name': 'Cart'});

      expect(result.success, isTrue);
      final providerPath = result.files.firstWhere(
        (f) => f.endsWith('cart_provider.dart'),
      );
      final content = File(providerPath).readAsStringSync();
      expect(
        content.trimLeft().startsWith('// GENERATED by zfa provider'),
        isTrue,
        reason: 'the provenance header must be the first thing in the file',
      );
      expect(
        content,
        contains('DO NOT EDIT'),
        reason: 'the header must say what hand-editing means',
      );
    },
  );

  test('provider create writes .zfa/receipts/provider-<Entity>.json recording '
      'interface, methods, stub count', () async {
    writeServiceInterface('Cart');

    await capability.execute({'name': 'Cart'});

    final receiptFile = File(
      ProviderReceiptWriter.receiptPath(project.path, 'Cart'),
    );
    expect(
      receiptFile.existsSync(),
      isTrue,
      reason: 'the deterministic provider receipt must exist',
    );

    final receipt =
        jsonDecode(receiptFile.readAsStringSync()) as Map<String, dynamic>;
    // proof.v1 envelope (what `zfa proof check` re-derives).
    expect(receipt['schema'], equals('proof.v1'));
    expect(receipt['command'], equals('zfa provider create'));
    expect(receipt['target'], equals('Cart'));
    final files = receipt['files'] as List;
    expect(files, isNotEmpty);
    expect(
      (files.first as Map<String, dynamic>)['path'],
      contains('cart_provider.dart'),
    );
    // Provider-specific ledger data (spec 979 order 1).
    expect(receipt['interface'], equals('CartService'));
    expect((receipt['methods'] as List).contains('execute'), isTrue);
    expect(receipt['stubCount'], equals(1));
  });

  test('zfa proof check covers providers: green on fresh generation, red on '
      'hand-edit', () async {
    writeServiceInterface('Cart');

    final result = await capability.execute({'name': 'Cart'});
    final providerPath = result.files.firstWhere(
      (f) => f.endsWith('cart_provider.dart'),
    );

    // Fresh generation: every digest re-derives — green.
    var report = await ProofChecker(projectRoot: project.path).check();
    expect(
      report.ok,
      isTrue,
      reason:
          'fresh generation must prove its artifacts: '
          '${report.findings.map((f) => f.detail).join('; ')}',
    );

    // Hand-edit: the digest no longer matches the receipt — red, with a
    // precise finding naming the tampered path.
    File(providerPath).writeAsStringSync(
      '${File(providerPath).readAsStringSync()}\n// hand-edit\n',
    );
    report = await ProofChecker(projectRoot: project.path).check();
    expect(report.ok, isFalse);
    expect(
      report.findings.any(
        (f) =>
            f.kind == ProofFinding.kindModified &&
            f.path.contains('cart_provider.dart'),
      ),
      isTrue,
      reason: 'a hand-edited provider must be reported as modified',
    );
  });

  test('ProviderReceiptWriter.load round-trips the receipt data', () async {
    writeServiceInterface('Cart');

    await capability.execute({'name': 'Cart'});

    final loaded = ProviderReceiptWriter.load(project.path, 'Cart');
    expect(loaded, isNotNull);
    expect(loaded!['interface'], equals('CartService'));
    expect(loaded['stubCount'], greaterThanOrEqualTo(1));
  });
}
