@Tags(['slow'])
// U2 (issue #1570, review round): the repair's synthesized implementations
// must COMPILE for every member shape the interface writer emits — the
// compile bar the fast unit file cannot provide (a name-only assertion
// misses the `Future<void>` stream body and the always-required `params`
// argument the review caught). Covers Future<T>, Future<List<T>>,
// Future<void> (parameter-less), Stream<T>, Stream<List<T>>, and the
// `--init` getter, asserted with a REAL `dart analyze` over the repaired
// interface + mock pair inside an engine-tier fixture package.
library;

import 'package:test/test.dart';
import 'package:zuraffa/src/core/context/file_system.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/mock/builders/mock_datasource_builder.dart';

import '../../helpers/engine_tier_fixture.dart';

const String _entitySource = '''
class ScanSession {
  final String id;
  const ScanSession(this.id);
}
''';

const String _mockDataSource = '''
import '../../domain/entities/scan_session/scan_session.dart';

class ScanSessionMockData {
  static const sampleScanSession = ScanSession('id-1');
  static const List<ScanSession> sampleList = [sampleScanSession];
}
''';

/// The interface exactly as `interface_generator.dart` emits it for
/// `--methods=get,getList,watch,watchList` plus `--init`
/// (`Stream<bool> get isInitialized`, `Future<void> dispose()`).
const String _interfaceSource = '''
// GENERATED by zfa datasource — DO NOT EDIT BY HAND.
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/scan_session/scan_session.dart';

abstract class ScanSessionDataSource with Loggable, FailureHandler {
  Future<ScanSession> get(QueryParams<ScanSession> params);
  Future<List<ScanSession>> getList(ListQueryParams<ScanSession> params);
  Future<void> dispose();
  Stream<ScanSession> watch(QueryParams<ScanSession> params);
  Stream<List<ScanSession>> watchList(ListQueryParams<ScanSession> params);
  Stream<bool> get isInitialized;
}
''';

/// The drifted mock: the class exists but declares no interface members
/// (created before the interface grew the current surface). Every member
/// in [_interfaceSource] is therefore synthesized by the shape-drift
/// repair, which is exactly the code under test.
const String _staleMockSource = '''
// Generated by zfa for: ScanSession
import 'dart:async';

import 'package:zuraffa/mock.dart';
import '../../../domain/entities/scan_session/scan_session.dart';
import '../../mock/scan_session_mock_data.dart';
import 'scan_session_datasource.dart';

class ScanSessionMockDataSource
    with Loggable, FailureHandler
    implements ScanSessionDataSource {
  final Duration _delay;

  ScanSessionMockDataSource({Duration? delay})
      : _delay = delay ?? const Duration(milliseconds: 100);
}
''';

void main() {
  late EngineTierFixture fx;

  setUpAll(() async {
    fx = await EngineTierFixture.create(name: 'mock_1570_compile_fixture');
    await fx.write(
      'lib/src/domain/entities/scan_session/scan_session.dart',
      _entitySource,
    );
    await fx.write(
      'lib/src/data/mock/scan_session_mock_data.dart',
      _mockDataSource,
    );
    await fx.write(
      'lib/src/data/datasources/scan_session/scan_session_datasource.dart',
      _interfaceSource,
    );
    await fx.write(
      'lib/src/data/datasources/scan_session/scan_session_mock_datasource.dart',
      _staleMockSource,
    );

    final result =
        await MockDataSourceBuilder(
          outputDir: fx.libSrc,
          fileSystem: FileSystem.create(),
        ).generateMockDataSource(
          GeneratorConfig(
            name: 'ScanSession',
            outputDir: fx.libSrc,
            methods: const [],
            generateMock: true,
          ),
        );
    expect(
      result.action,
      'updated',
      reason: 'every missing interface member must be repaired',
    );

    await fx.pubGet();
  });

  tearDownAll(() async {
    await fx.dispose();
  });

  test('the repair synthesizes a compiling signature for every member '
      'shape the interface writer emits', () async {
    final repaired = fx.read(
      'lib/src/data/datasources/scan_session/scan_session_mock_datasource.dart',
    );

    // Future<T> / Future<List<T>> — sample fixture bodies.
    expect(repaired, contains('Future<ScanSession> get('));
    expect(repaired, contains('Future<List<ScanSession>> getList('));
    expect(repaired, contains('ScanSessionMockData.sampleScanSession'));
    expect(repaired, contains('ScanSessionMockData.sampleList'));

    // Future<void> — mirrored WITHOUT a `params` argument (the interface
    // member declares none; a required NoParams params is invalid_override).
    expect(repaired, contains('Future<void> dispose()'));
    expect(
      repaired,
      isNot(contains('dispose(NoParams')),
      reason: 'a parameter-less member must not gain a params argument',
    );

    // Stream<T> / Stream<List<T>> — the delayed future must be typed
    // `Future<T>` so `Stream.fromFuture` yields `Stream<T>` (Future<void>
    // yields Stream<void> and fails argument_type_not_assignable).
    expect(repaired, contains('Future<ScanSession>.delayed('));
    expect(repaired, contains('Future<List<ScanSession>>.delayed('));
    expect(
      repaired,
      isNot(contains('Future<void>.delayed(_delay, () =>')),
      reason: 'the stream body must not be typed Future<void>',
    );

    // The --init getter stays a getter (a method declaration would be
    // conflicting_method_and_field against the interface's field).
    expect(repaired, contains('Stream<bool> get isInitialized'));
  }, timeout: const Timeout(Duration(minutes: 3)));

  test('the repaired interface + mock pair passes a real scoped '
      'dart analyze with zero errors', () async {
    final result = await fx.analyzeLib();
    expect(
      result.exitCode,
      0,
      reason:
          'the repaired mock must compile against its interface.\n'
          '${result.stdout}\n${result.stderr}',
    );
  }, timeout: const Timeout(Duration(minutes: 3)));
}
