// Issue #1880: arbitrary (and shape-mismatched CRUD) verbs must be emitted
// from the DECLARED interface signature, not from the call-wide
// `--params` / `--returns` template — otherwise the mock contradicts the
// contract test and `--certify` fails with `invalid_override`.
//
// The review of #1911 (issue #1911) extended the bar: the synthesizer must
// also emit values compatible with the declared return type (scalars,
// sync members), must not claim multi-parameter shapes it cannot mirror,
// and must compare the COMPLETE CRUD parameter type.
import 'dart:io';

import 'package:test/test.dart';
import 'package:zuraffa/src/core/context/file_system.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/mock/builders/mock_datasource_builder.dart';

const _entitySource = '''
class ScanSession {
  final String id;
  const ScanSession(this.id);

  ScanSession copyWithField(Object field, Object? value) => this;
}

class ScanSessionPatch {}

class Credentials {}
''';

String _interface(String members) =>
    '''
// GENERATED by zfa datasource — DO NOT EDIT BY HAND.
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/scan_session/scan_session.dart';

abstract class ScanSessionDataSource with Loggable, FailureHandler {
$members
}
''';

GeneratorConfig _config(List<String> methods, {String idFieldType = 'String'}) {
  return GeneratorConfig(
    name: 'ScanSession',
    outputDir: '/tmp/unused-output-dir',
    methods: methods,
    generateMock: true,
    generateDataSource: false,
    idFieldType: idFieldType,
  );
}

Future<String> _seedTree(String outputDir, {required String members}) async {
  final entityDir = Directory('$outputDir/domain/entities/scan_session');
  await entityDir.create(recursive: true);
  await File(
    '${entityDir.path}/scan_session.dart',
  ).writeAsString(_entitySource);

  final dsDir = Directory('$outputDir/data/datasources/scan_session');
  await dsDir.create(recursive: true);
  await File(
    '${dsDir.path}/scan_session_datasource.dart',
  ).writeAsString(_interface(members));
  return '${dsDir.path}/scan_session_mock_datasource.dart';
}

MockDataSourceBuilder _builder(String outputDir) => MockDataSourceBuilder(
  outputDir: outputDir,
  fileSystem: FileSystem.create(),
);

void main() {
  late Directory tempDir;
  late String outputDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('zuraffa_1880_');
    outputDir = Directory('${tempDir.path}/lib/src').path;
  });

  tearDown(() async {
    if (tempDir.existsSync()) {
      tempDir.deleteSync(recursive: true);
    }
  });

  group('issue #1880 — interface-derived signatures', () {
    test('zero-arg arbitrary verb emits with no params argument', () async {
      final mockPath = await _seedTree(
        outputDir,
        members: '  Future<ScanSession> load();',
      );

      await _builder(outputDir).generateMockDataSource(_config(const ['load']));

      final source = await File(mockPath).readAsString();
      expect(
        source,
        contains('Future<ScanSession> load() async'),
        reason: 'the zero-arg declaration must not gain a params argument',
      );
      expect(
        source,
        contains('ScanSessionMockData.sampleScanSession'),
        reason: 'an entity return keeps the typed sample fixture',
      );
      expect(source, isNot(contains('load(QueryParams')));
    });

    test('stream-shaped arbitrary verb stays a stream', () async {
      final mockPath = await _seedTree(
        outputDir,
        members: '  Stream<ScanSession> watchAll();',
      );

      await _builder(
        outputDir,
      ).generateMockDataSource(_config(const ['watchAll']));

      final source = await File(mockPath).readAsString();
      expect(source, contains('Stream<ScanSession> watchAll()'));
      expect(source, contains('Future<ScanSession>.delayed'));
      expect(source, isNot(contains('Future<Stream<')));
    });

    test(
      'scalar return emits a compatible literal, not an entity sample',
      () async {
        final mockPath = await _seedTree(
          outputDir,
          members: '  Future<bool> isReady();',
        );

        await _builder(
          outputDir,
        ).generateMockDataSource(_config(const ['isReady']));

        final source = await File(mockPath).readAsString();
        expect(source, contains('Future<bool> isReady() async'));
        expect(source, contains('return true;'));
        expect(
          source,
          isNot(contains('sampleScanSession')),
          reason: 'an entity sample under a bool return does not compile',
        );
      },
    );

    test('synchronous member stays synchronous', () async {
      final mockPath = await _seedTree(outputDir, members: '  bool isOpen();');

      await _builder(
        outputDir,
      ).generateMockDataSource(_config(const ['isOpen']));

      final source = await File(mockPath).readAsString();
      expect(source, contains('bool isOpen()'));
      expect(
        source,
        isNot(contains('Future<bool> isOpen')),
        reason: 'wrapping a sync member in Future<> is invalid_override',
      );
    });

    test('CRUD verb compares the complete parameter type', () async {
      final mockPath = await _seedTree(
        outputDir,
        members:
            '  Future<ScanSession> update('
            'UpdateParams<int, ScanSessionPatch> params);',
      );

      await _builder(
        outputDir,
      ).generateMockDataSource(_config(const ['update']));

      final source = await File(mockPath).readAsString();
      expect(
        source,
        contains('UpdateParams<int, ScanSessionPatch> params'),
        reason: 'the interface declaration, not the String-id config, wins',
      );
      expect(source, isNot(contains('UpdateParams<String, ScanSessionPatch>')));
    });

    test('multi-parameter declarations are rejected, never narrowed', () async {
      await _seedTree(
        outputDir,
        members:
            '  Future<ScanSession> update('
            'UpdateParams<String, ScanSessionPatch> params, String extra);',
      );

      await expectLater(
        _builder(outputDir).generateMockDataSource(_config(const ['update'])),
        throwsA(
          isA<ArgumentError>().having(
            (e) => e.message.toString(),
            'message',
            contains('cannot be synthesized'),
          ),
        ),
        reason: 'a one-parameter override would still fail invalid_override',
      );
    });

    test('return shapes with no honest fixture are rejected', () async {
      await _seedTree(
        outputDir,
        members: '  Future<Credentials> credentials();',
      );

      await expectLater(
        _builder(
          outputDir,
        ).generateMockDataSource(_config(const ['credentials'])),
        throwsA(
          isA<ArgumentError>().having(
            (e) => e.message.toString(),
            'message',
            contains('cannot be synthesized'),
          ),
        ),
        reason: 'returning an entity sample under Credentials does not compile',
      );
    });
  });
}
