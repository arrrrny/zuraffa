// Issue #1922: `zfa mock create --force` validated arbitrary member shapes
// only AFTER it had already rewritten `<Entity>DataSource`. A refused member
// (an unknown return type, the #1850 "honest bodies" ArgumentError) exited 1
// and left the interface clobbered — hand-maintained re-exports and declared
// parameter names gone, with no rollback.
//
// Contract pinned here: every member shape is validated BEFORE the first
// write, so a refused run leaves the working tree byte-identical.
import 'dart:io';

import 'package:test/test.dart';
import 'package:zuraffa/src/core/generator_options.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/mock/builders/mock_builder.dart';

// Issue #1747: the CRUD surface `zfa mock create` requires before it emits
// the datasource/provider pair — declared inline.
const _entityFileContent = '''
class Deal {
  final String id;
  const Deal(this.id);

  Deal copyWithField(Object field, Object? value) => this;
}

class DealPatch {}
''';

// Hand-maintained interface content the issue reproduces: it carries a
// workaround re-export (#1856 class) and a declared parameter name that the
// generator's generic `params` never reproduces.
const _handMaintainedInterface = '''
// GENERATED by zfa datasource — DO NOT EDIT BY HAND.
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/deal/deal.dart';

// WORKAROUND (arrrrny/zuraffa#1856): re-export makes the name resolvable.
export '../../../domain/entities/deal_page/deal_page.dart';

abstract class DealDataSource with Loggable, FailureHandler {
  /// Removes the saved deal with [id]; idempotent for an id that is not saved.
  Future<void> remove(String id);
}
''';

GeneratorConfig _config({
  required String outputDir,
  required List<String> methods,
}) {
  return GeneratorConfig(
    name: 'Deal',
    outputDir: outputDir,
    methods: methods,
    generateMock: true,
    generateDataSource: false,
    force: true,
  );
}

MockBuilder _builder(String outputDir) => MockBuilder(
  outputDir: outputDir,
  options: const GeneratorOptions(dryRun: false, force: true, verbose: false),
);

Future<String> _seedHandMaintainedTree(String outputDir) async {
  final entityDir = Directory('$outputDir/domain/entities/deal');
  await entityDir.create(recursive: true);
  await File('${entityDir.path}/deal.dart').writeAsString(_entityFileContent);

  final dsDir = Directory('$outputDir/data/datasources/deal');
  await dsDir.create(recursive: true);
  final interfacePath = '${dsDir.path}/deal_datasource.dart';
  await File(interfacePath).writeAsString(_handMaintainedInterface);
  return interfacePath;
}

void main() {
  late Directory tempDir;
  late String outputDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('zuraffa_1922_');
    outputDir = Directory('${tempDir.path}/lib/src').path;
  });

  tearDown(() async {
    if (tempDir.existsSync()) {
      tempDir.deleteSync(recursive: true);
    }
  });

  group('A1 — a refused member leaves the tree untouched (issue #1922)', () {
    test('interface bytes are identical after the refusal', () async {
      final interfacePath = await _seedHandMaintainedTree(outputDir);
      final before = await File(interfacePath).readAsString();

      await expectLater(
        _builder(outputDir).generate(
          _config(
            outputDir: outputDir,
            methods: const [
              'removeDeals:ListQueryParams<Deal>->DealPage',
              'remove:String->void',
            ],
          ),
        ),
        throwsA(
          isA<ArgumentError>().having(
            (e) => e.message,
            'message',
            'unknown return type DealPage for member removeDeals',
          ),
        ),
      );

      expect(
        await File(interfacePath).readAsString(),
        before,
        reason: 'the refused run must not rewrite the datasource interface',
      );
      expect(
        File(interfacePath).readAsStringSync(),
        contains("export '../../../domain/entities/deal_page/deal_page.dart';"),
        reason: 'the hand-maintained #1856 workaround re-export survives',
      );
      expect(
        File(interfacePath).readAsStringSync(),
        contains('Future<void> remove(String id);'),
        reason: 'the declared parameter name survives',
      );
    });

    test('no other generated file is written by the refused run', () async {
      final interfacePath = await _seedHandMaintainedTree(outputDir);

      await expectLater(
        _builder(outputDir).generate(
          _config(
            outputDir: outputDir,
            methods: const [
              'removeDeals:ListQueryParams<Deal>->DealPage',
              'remove:String->void',
            ],
          ),
        ),
        throwsA(isA<ArgumentError>()),
      );

      final mockDatasource = File(
        '$outputDir/data/datasources/deal/deal_mock_datasource.dart',
      );
      expect(
        mockDatasource.existsSync(),
        isFalse,
        reason: 'the mock datasource is emitted only after validation',
      );
      final mockData = File('$outputDir/data/mock/deal_mock_data.dart');
      expect(
        mockData.existsSync(),
        isFalse,
        reason: 'no fixture is written by a refused run either',
      );
      expect(File(interfacePath).existsSync(), isTrue);
    });
  });

  group('A2 — valid member shapes still generate', () {
    test('a void arbitrary member is accepted and emitted', () async {
      await _seedHandMaintainedTree(outputDir);

      final files = await _builder(outputDir).generate(
        _config(outputDir: outputDir, methods: const ['remove:String->void']),
      );

      expect(
        files.map((f) => f.path),
        contains(endsWith('deal_mock_datasource.dart')),
      );
      expect(
        File(
          '$outputDir/data/datasources/deal/deal_mock_datasource.dart',
        ).readAsStringSync(),
        contains('Future<void> remove(String params)'),
      );
    });
  });
}
