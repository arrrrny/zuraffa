// Issue #1418: `mock create --force` regenerated the mock datasource but
// left the STALE `<entity>_datasource.dart` interface (create-if-absent
// write path). The pair drifted — `Missing concrete implementation of
// 'DealDataSource.list'` — and `--certify` dead-ended no matter how many
// times `--force` re-ran. The fix makes the force run regenerate the
// interface together with the mock, while the non-force path keeps the
// create-if-absent contract byte-for-byte.
import 'dart:io';

import 'package:test/test.dart';
import 'package:zuraffa/src/core/generator_options.dart';
import 'package:zuraffa/src/core/context/file_system.dart';
import 'package:zuraffa/src/models/generated_file.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/mock/builders/mock_builder.dart';
import 'package:zuraffa/src/plugins/mock/services/mock_staleness_detector.dart';
import 'package:zuraffa/src/utils/method_extractor.dart';

const _entityFileContent =
    'class Deal { final String id; const Deal(this.id); }';

// The stale interface the issue reproduces: written by run 1
// (`--methods list`), never touched by run 2 (`--methods getList --force`).
const _staleInterface = '''
// GENERATED by zfa datasource — DO NOT EDIT BY HAND.
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/deal/deal.dart';

abstract class DealDataSource with Loggable, FailureHandler {
  Future<Deal> list(NoParams params);
}
''';

const _staleMockWithListOnly = '''
// Generated by zfa for: Deal
import 'dart:async';

import 'package:zuraffa/mock.dart';
import '../../../domain/entities/deal/deal.dart';
import '../../mock/deal_mock_data.dart';
import 'deal_datasource.dart';

class DealMockDataSource with Loggable, FailureHandler implements DealDataSource {
  final Duration _delay;

  DealMockDataSource({Duration? delay})
      : _delay = delay ?? const Duration(milliseconds: 100);

  @override
  Future<Deal> list(NoParams params) async {
    logger.info('list called');
    await Future<void>.delayed(_delay);
    return DealMockData.sampleDeal;
  }
}
''';

GeneratorConfig _config({
  required String outputDir,
  bool force = false,
  bool revert = false,
  bool dryRun = false,
  List<String> methods = const ['getList'],
  String? repo,
}) {
  return GeneratorConfig(
    name: 'Deal',
    outputDir: outputDir,
    methods: methods,
    generateMock: true,
    generateDataSource: false,
    force: force,
    revert: revert,
    dryRun: dryRun,
    repo: repo,
  );
}

MockBuilder _builder(String outputDir, {bool force = false}) => MockBuilder(
  outputDir: outputDir,
  options: GeneratorOptions(dryRun: false, force: force, verbose: false),
);

/// Seeds the tree: entity + stale interface declaring `list(NoParams)` +
/// in-sync stale mock implementing `list` only. Returns (interfacePath,
/// interfaceBytesBefore, mockPath).
Future<({String interfacePath, String interfaceBytes, String mockPath})>
_seedDriftedTree(String outputDir, {String? interfaceContent}) async {
  final entityDir = Directory('$outputDir/domain/entities/deal');
  await entityDir.create(recursive: true);
  await File('${entityDir.path}/deal.dart').writeAsString(_entityFileContent);

  final dsDir = Directory('$outputDir/data/datasources/deal');
  await dsDir.create(recursive: true);
  final interfacePath = '${dsDir.path}/deal_datasource.dart';
  await File(interfacePath).writeAsString(interfaceContent ?? _staleInterface);
  final mockPath = '${dsDir.path}/deal_mock_datasource.dart';
  await File(mockPath).writeAsString(_staleMockWithListOnly);
  return (
    interfacePath: interfacePath,
    interfaceBytes: await File(interfacePath).readAsString(),
    mockPath: mockPath,
  );
}

Future<({String interfacePath, String mockPath})> _seedFreshTree(
  String outputDir,
) async {
  final entityDir = Directory('$outputDir/domain/entities/deal');
  await entityDir.create(recursive: true);
  await File('${entityDir.path}/deal.dart').writeAsString(_entityFileContent);
  final dsDir = Directory('$outputDir/data/datasources/deal');
  await dsDir.create(recursive: true);
  return (
    interfacePath: '${dsDir.path}/deal_datasource.dart',
    mockPath: '${dsDir.path}/deal_mock_datasource.dart',
  );
}

GeneratedFile? _ledgerEntry(List<GeneratedFile> files, String suffix) {
  for (final f in files) {
    if (f.path.endsWith(suffix)) return f;
  }
  return null;
}

void main() {
  late Directory tempDir;
  late String outputDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('zuraffa_1418_');
    outputDir = Directory('${tempDir.path}/lib/src').path;
  });

  tearDown(() async {
    if (tempDir.existsSync()) {
      tempDir.deleteSync(recursive: true);
    }
  });

  group('A1 — force regenerates the stale interface (issue #1418)', () {
    test('interface is rewritten from the current --methods', () async {
      final seeded = await _seedDriftedTree(outputDir);

      final files = await _builder(
        outputDir,
        force: true,
      ).generate(_config(outputDir: outputDir, force: true));

      final entry = _ledgerEntry(files, 'deal_datasource.dart');
      expect(entry, isNotNull, reason: 'the interface must reach the ledger');
      expect(entry!.action, 'overwritten');

      final regenerated = await File(seeded.interfacePath).readAsString();
      expect(
        regenerated,
        contains('getList(ListQueryParams<Deal> params)'),
        reason: 'the regenerated interface declares the CURRENT methods',
      );
      expect(
        regenerated,
        isNot(contains('list(NoParams')),
        reason: 'the stale member the current methods dropped is gone',
      );
    });

    test(
      'mock-side ledger entry is overwritten too (pair regenerated)',
      () async {
        await _seedDriftedTree(outputDir);

        final files = await _builder(
          outputDir,
          force: true,
        ).generate(_config(outputDir: outputDir, force: true));

        final mockEntry = _ledgerEntry(files, 'deal_mock_datasource.dart');
        expect(mockEntry, isNotNull);
        expect(mockEntry!.action, 'overwritten');
      },
    );
  });

  group('A2 — the force-regenerated pair conforms', () {
    test('interface members ⊆ mock members (certification oracle)', () async {
      final seeded = await _seedDriftedTree(outputDir);

      await _builder(
        outputDir,
        force: true,
      ).generate(_config(outputDir: outputDir, force: true));

      final interfaceMembers =
          await MethodExtractor.extractMethodsFromInterface(
            seeded.interfacePath,
            'DealDataSource',
          );
      expect(interfaceMembers.map((m) => m.fieldName), ['getList']);

      final missing = await MockStalenessDetector.detectMockStaleness(
        interfacePath: seeded.interfacePath,
        interfaceClass: 'DealDataSource',
        mockPath: seeded.mockPath,
        mockClass: 'DealMockDataSource',
        fileSystem: FileSystem.create(),
      );
      expect(
        missing,
        isEmpty,
        reason:
            'the structural check the certification runs finds nothing '
            'missing on the force-regenerated pair',
      );
    });
  });

  group('A3 — non-force leaves the interface byte-identical', () {
    test('create-if-absent contract preserved; in-sync mock skipped', () async {
      final seeded = await _seedDriftedTree(outputDir);

      final files = await _builder(
        outputDir,
      ).generate(_config(outputDir: outputDir));

      // The interface writer was never invoked — no ledger entry at all.
      final entry = _ledgerEntry(files, 'deal_datasource.dart');
      expect(
        entry,
        isNull,
        reason:
            'a non-force run must not touch the existing interface (the '
            'create-if-absent contract and the #1570 hard constraint)',
      );
      final after = await File(seeded.interfacePath).readAsString();
      expect(after, seeded.interfaceBytes);

      // The mock is in sync with the stale interface → #1570 skip holds.
      final mockEntry = _ledgerEntry(files, 'deal_mock_datasource.dart');
      expect(mockEntry, isNotNull);
      expect(mockEntry!.action, 'skipped');
    });
  });

  group('A4 — absent interface is emitted in both modes', () {
    test('non-force emits the missing interface once (created)', () async {
      final seeded = await _seedFreshTree(outputDir);

      final files = await _builder(
        outputDir,
      ).generate(_config(outputDir: outputDir));

      final entry = _ledgerEntry(files, 'deal_datasource.dart');
      expect(entry, isNotNull);
      expect(entry!.action, 'created');
      expect(File(seeded.interfacePath).existsSync(), isTrue);
    });

    test('force emits the missing interface once (created)', () async {
      final seeded = await _seedFreshTree(outputDir);

      final files = await _builder(
        outputDir,
        force: true,
      ).generate(_config(outputDir: outputDir, force: true));

      final entry = _ledgerEntry(files, 'deal_datasource.dart');
      expect(entry, isNotNull);
      expect(entry!.action, 'created');
      expect(File(seeded.interfacePath).existsSync(), isTrue);
    });
  });

  group('U1 — force honors dryRun', () {
    test('no bytes change; ledger carries the would-be regeneration', () async {
      final seeded = await _seedDriftedTree(outputDir);

      final files = await MockBuilder(
        outputDir: outputDir,
        options: const GeneratorOptions(
          dryRun: true,
          force: true,
          verbose: false,
        ),
      ).generate(_config(outputDir: outputDir, force: true, dryRun: true));

      final after = await File(seeded.interfacePath).readAsString();
      expect(after, seeded.interfaceBytes, reason: 'dry-run never writes');
      final entry = _ledgerEntry(files, 'deal_datasource.dart');
      expect(entry, isNotNull);
      expect(
        entry!.action,
        'overwritten',
        reason: 'the ledger still reports the WOULD-BE regeneration',
      );
    });
  });

  group('U2 — force + revert: revert precedence wins', () {
    test(
      'the interface regeneration guard does not fire over revert',
      () async {
        final seeded = await _seedDriftedTree(outputDir);

        await _builder(
          outputDir,
          force: true,
        ).generate(_config(outputDir: outputDir, force: true, revert: true));

        final after = await File(seeded.interfacePath).readAsString();
        expect(
          after,
          seeded.interfaceBytes,
          reason:
              'force && !revert arms the regeneration — with revert the '
              'revert contract keeps the interface writer out',
        );
      },
    );
  });

  group('U3 — repo-derived path stability', () {
    test(
      'repo config regenerates the SAME interface path, no second file',
      () async {
        final seeded = await _seedDriftedTree(outputDir);

        final files = await _builder(outputDir, force: true).generate(
          _config(outputDir: outputDir, force: true, repo: 'DealRepository'),
        );

        final entry = _ledgerEntry(files, 'deal_datasource.dart');
        expect(entry, isNotNull);
        expect(entry!.action, 'overwritten');
        expect(entry.path, seeded.interfacePath);
        final regenerated = await File(seeded.interfacePath).readAsString();
        expect(regenerated, contains('getList(ListQueryParams<Deal> params)'));
        // No repo-name-derived second interface file anywhere in the tree.
        final stray = _ledgerEntry(files, 'deal_repository_datasource.dart');
        expect(stray, isNull);
      },
    );
  });

  group('U4 — idempotent force runs', () {
    test('two consecutive force runs are byte-stable', () async {
      await _seedDriftedTree(outputDir);
      final builder = _builder(outputDir, force: true);
      final config = _config(outputDir: outputDir, force: true);

      await builder.generate(config);
      final interfaceRun1 = await File(
        '$outputDir/data/datasources/deal/deal_datasource.dart',
      ).readAsString();
      final mockRun1 = await File(
        '$outputDir/data/datasources/deal/deal_mock_datasource.dart',
      ).readAsString();

      await builder.generate(config);
      final interfaceRun2 = await File(
        '$outputDir/data/datasources/deal/deal_datasource.dart',
      ).readAsString();
      final mockRun2 = await File(
        '$outputDir/data/datasources/deal/deal_mock_datasource.dart',
      ).readAsString();

      expect(interfaceRun2, interfaceRun1);
      expect(mockRun2, mockRun1);
    });
  });
}
