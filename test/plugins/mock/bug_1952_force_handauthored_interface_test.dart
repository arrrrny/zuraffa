// Issue #1952: `zfa mock create --force` silently replaces a hand-authored
// `<Entity>DataSource` interface (members the run's `--methods` cannot
// reproduce, e.g. `recent` / `record` / `clear`) with the generated CRUD
// surface, then certifies against the interface it just overwrote — exit 0,
// the destructive contract change invisible to a scripted pipeline.
//
// Contract pinned here: when a force run would overwrite an EXISTING
// declared interface with a member set that loses a member outside the
// generator's interface vocabulary, the run is REFUSED before the first
// write — naming the file and the lost members — unless
// `--overwrite-interface` opts in. Lost CRUD-vocabulary members stay the
// #1418 methods-driven drift and keep regenerating.
import 'dart:io';

import 'package:test/test.dart';
import 'package:zuraffa/src/core/generator_options.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/mock/builders/mock_builder.dart';

// Issue #1747: the CRUD surface `zfa mock create` requires before it emits
// the datasource/provider pair — declared inline.
const _entityFileContent = '''
class Deal {
  final String id;
  const Deal(this.id);

  Deal copyWithField(Object field, Object? value) => this;
}

class DealPatch {}
''';

// The hand-authored interface the issue reproduces (#1952's SearchQuery
// shape): declared members outside the generator's CRUD vocabulary, no
// generated provenance header.
const _handAuthoredInterface = '''
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/deal/deal.dart';

abstract class DealDataSource with Loggable, FailureHandler {
  Future<List<Deal>> recent();
  Future<void> record(Deal query);
  Future<void> clear();
}
''';

// The stale GENERATED interface #1418 reproduces: a CRUD-vocabulary member
// the current `--methods` dropped. Force must keep regenerating it.
const _staleGeneratedInterface = '''
// GENERATED by zfa datasource — DO NOT EDIT BY HAND.
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/deal/deal.dart';

abstract class DealDataSource with Loggable, FailureHandler {
  Future<Deal> list(NoParams params);
}
''';

GeneratorConfig _config({
  required String outputDir,
  bool force = false,
  List<String> methods = const ['get', 'update', 'toggle'],
  bool overwriteInterface = false,
  bool appendToExisting = false,
}) {
  return GeneratorConfig(
    name: 'Deal',
    outputDir: outputDir,
    methods: methods,
    generateMock: true,
    generateDataSource: false,
    force: force,
    overwriteInterface: overwriteInterface,
    appendToExisting: appendToExisting,
  );
}

MockBuilder _builder(String outputDir, {bool force = false}) => MockBuilder(
  outputDir: outputDir,
  options: GeneratorOptions(dryRun: false, force: force, verbose: false),
);

/// Seeds the entity plus a datasource interface; returns the interface path.
Future<String> _seedTree(
  String outputDir,
  String interfaceContent, {
  bool withMockDatasource = false,
}) async {
  final entityDir = Directory('$outputDir/domain/entities/deal');
  await entityDir.create(recursive: true);
  await File('${entityDir.path}/deal.dart').writeAsString(_entityFileContent);

  final dsDir = Directory('$outputDir/data/datasources/deal');
  await dsDir.create(recursive: true);
  final interfacePath = '${dsDir.path}/deal_datasource.dart';
  await File(interfacePath).writeAsString(interfaceContent);
  if (withMockDatasource) {
    await File(
      '${dsDir.path}/deal_mock_datasource.dart',
    ).writeAsString('// placeholder\n');
  }
  return interfacePath;
}

void main() {
  late Directory tempDir;
  late String outputDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('zuraffa_1952_');
    outputDir = Directory('${tempDir.path}/lib/src').path;
  });

  tearDown(() async {
    if (tempDir.existsSync()) {
      tempDir.deleteSync(recursive: true);
    }
  });

  group('A1 — force refuses a hand-authored interface (issue #1952)', () {
    test(
      'the run throws, naming the file and the members that would be lost',
      () async {
        await _seedTree(outputDir, _handAuthoredInterface);

        await expectLater(
          _builder(
            outputDir,
            force: true,
          ).generate(_config(outputDir: outputDir, force: true)),
          throwsA(
            isA<StateError>()
                .having(
                  (e) => e.message,
                  'message',
                  contains('deal_datasource.dart'),
                )
                .having((e) => e.message, 'message', contains('recent'))
                .having((e) => e.message, 'message', contains('record'))
                .having((e) => e.message, 'message', contains('clear')),
          ),
        );
      },
    );

    test('the refused run leaves the tree byte-identical', () async {
      final interfacePath = await _seedTree(outputDir, _handAuthoredInterface);
      final before = await File(interfacePath).readAsString();

      try {
        await _builder(
          outputDir,
          force: true,
        ).generate(_config(outputDir: outputDir, force: true));
      } catch (_) {
        // The refusal is asserted in A1; here only the tree matters.
      }

      expect(
        await File(interfacePath).readAsString(),
        before,
        reason: 'the refused run must not rewrite the declared interface',
      );
      expect(
        File(
          '$outputDir/data/datasources/deal/deal_mock_datasource.dart',
        ).existsSync(),
        isFalse,
        reason: 'no mock datasource is written by a refused run',
      );
      expect(
        File('$outputDir/data/mock/deal_mock_data.dart').existsSync(),
        isFalse,
        reason: 'no fixture is written by a refused run either',
      );
    });
  });

  group('A2 — --overwrite-interface opts in to the destructive run', () {
    test('the interface is overwritten and the mock is emitted', () async {
      final interfacePath = await _seedTree(outputDir, _handAuthoredInterface);

      final files = await _builder(outputDir, force: true).generate(
        _config(outputDir: outputDir, force: true, overwriteInterface: true),
      );

      expect(
        File(interfacePath).readAsStringSync(),
        contains('Future<Deal> get(QueryParams<Deal> params)'),
        reason: 'the opt-in run overwrites the interface with the CRUD set',
      );
      expect(
        files.map((f) => f.path),
        contains(endsWith('deal_mock_datasource.dart')),
      );
    });
  });

  group('A3 — force + append is a lossless run, never refused', () {
    test(
      'the hand members survive and the planned members are appended',
      () async {
        final interfacePath = await _seedTree(
          outputDir,
          _handAuthoredInterface,
        );

        final files = await _builder(outputDir, force: true).generate(
          _config(outputDir: outputDir, force: true, appendToExisting: true),
        );

        final after = File(interfacePath).readAsStringSync();
        expect(
          after,
          contains('recent()'),
          reason:
              'the append branch never removes members — the run is lossless',
        );
        expect(
          after,
          contains('Future<Deal> get(QueryParams<Deal> params)'),
          reason: 'the planned CRUD members are appended to the interface',
        );
        expect(
          files.map((f) => f.path),
          contains(endsWith('deal_mock_datasource.dart')),
        );
      },
    );
  });

  group('B1 — #1418 holds: lost CRUD members still regenerate', () {
    test('a stale generated interface (CRUD member dropped by --methods) is '
        'rewritten from the current methods', () async {
      final interfacePath = await _seedTree(
        outputDir,
        _staleGeneratedInterface,
      );

      final files = await _builder(
        outputDir,
        force: true,
      ).generate(_config(outputDir: outputDir, force: true));

      expect(
        File(interfacePath).readAsStringSync(),
        contains('Future<Deal> get(QueryParams<Deal> params)'),
        reason: 'the #1418 methods-driven drift stays legal',
      );
      expect(
        File(interfacePath).readAsStringSync(),
        isNot(contains('list(NoParams')),
      );
      expect(
        files.map((f) => f.path),
        contains(endsWith('deal_mock_datasource.dart')),
      );
    });
  });

  group('B2 — no lost members: force regeneration proceeds', () {
    test('idempotent force run over its own generated interface', () async {
      final freshDir = Directory('${tempDir.path}/fresh/lib/src')
        ..createSync(recursive: true);
      final entityDir = Directory('${freshDir.path}/domain/entities/deal');
      entityDir.createSync(recursive: true);
      await File(
        '${entityDir.path}/deal.dart',
      ).writeAsString(_entityFileContent);

      final builder = _builder(freshDir.path, force: true);
      final config = _config(outputDir: freshDir.path, force: true);

      await builder.generate(config);
      final interfacePath =
          '${freshDir.path}/data/datasources/deal/deal_datasource.dart';
      final run1 = await File(interfacePath).readAsString();

      await builder.generate(config);
      expect(
        await File(interfacePath).readAsString(),
        run1,
        reason: 'the second force run loses nothing and stays byte-stable',
      );
    });
  });

  group('C1 — only the non-vocabulary losses are named', () {
    test('an interface with CRUD get + hand-authored recent refuses naming '
        'recent only', () async {
      final interfacePath = await _seedTree(outputDir, '''
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/deal/deal.dart';

abstract class DealDataSource with Loggable, FailureHandler {
  Future<Deal> get(QueryParams<Deal> params);
  Future<List<Deal>> recent();
}
''');
      final before = await File(interfacePath).readAsString();

      await expectLater(
        _builder(
          outputDir,
          force: true,
        ).generate(_config(outputDir: outputDir, force: true)),
        throwsA(
          isA<StateError>().having(
            (e) => e.message,
            'message',
            allOf(contains('recent'), isNot(contains('get,'))),
          ),
        ),
      );
      expect(
        await File(interfacePath).readAsString(),
        before,
        reason: 'the refused run must not rewrite the declared interface',
      );
    });
  });

  group('C2 — non-force keeps the create-if-absent contract', () {
    test('an existing hand-authored interface is never touched', () async {
      final interfacePath = await _seedTree(outputDir, _handAuthoredInterface);
      final before = await File(interfacePath).readAsString();

      await _builder(outputDir).generate(_config(outputDir: outputDir));

      expect(
        await File(interfacePath).readAsString(),
        before,
        reason: 'without --force the #417 create-if-absent contract holds',
      );
    });
  });

  group('D — overwriteInterface round-trips through JSON', () {
    test('toJson emits the key and fromJson reads it back', () {
      final on = _config(outputDir: outputDir, overwriteInterface: true);
      expect(on.toJson()['overwrite_interface'], isTrue);
      expect(
        GeneratorConfig.fromJson({
          'overwrite_interface': true,
        }, 'Deal').overwriteInterface,
        isTrue,
        reason:
            'a JSON replay of an --overwrite-interface run '
            'must keep the opt-in',
      );

      expect(
        GeneratorConfig.fromJson({
          'overwrite_interface': false,
        }, 'Deal').overwriteInterface,
        isFalse,
      );
      // Workaround (arrrrny/zuraffa#1962): the assertions above test the two
      // directions separately instead of a full `fromJson(toJson())`
      // round-trip — that round-trip crashes today on the pre-existing
      // bool-vs-String? overload of the presenter/controller keys, unrelated
      // to `overwrite_interface`. When #1962 lands, tighten this to the full
      // round-trip.
    });
  });
}
