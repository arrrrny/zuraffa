// Issue #1570: the mock lane's skip decision is shape-based, not
// existence-based. A certified mock created earlier (e.g. `mock create
// --methods=get`) must gain the members the interface later appended
// (`zfa make --methods=get,getList`) instead of being skipped on
// "file exists" — the drift that dead-ends `zfa build` with
// non_abstract_class_inherits_abstract_member.
import 'dart:async';
import 'dart:io';

import 'package:test/test.dart';
import 'package:zuraffa/src/core/generator_options.dart';
import 'package:zuraffa/src/core/context/file_system.dart';
import 'package:zuraffa/src/models/generator_config.dart';
import 'package:zuraffa/src/plugins/mock/builders/mock_datasource_builder.dart';
import 'package:zuraffa/src/plugins/mock/mock_plugin.dart';

const _entityFileContent =
    'class ScanSession { final String id; const ScanSession(this.id); }';

const _interfaceWithGetList = '''
// GENERATED by zfa datasource — DO NOT EDIT BY HAND.
import 'package:zuraffa/zuraffa.dart';

import '../../../domain/entities/scan_session/scan_session.dart';

abstract class ScanSessionDataSource with Loggable, FailureHandler {
  Future<ScanSession> get(QueryParams<ScanSession> params);
  Future<List<ScanSession>> getList(ListQueryParams<ScanSession> params);
}
''';

const _staleMockWithGetOnly = '''
// Generated by zfa for: ScanSession
import 'dart:async';

import 'package:zuraffa/mock.dart';
import '../../../domain/entities/scan_session/scan_session.dart';
import '../../mock/scan_session_mock_data.dart';
import 'scan_session_datasource.dart';

class ScanSessionMockDataSource with Loggable, FailureHandler implements ScanSessionDataSource {
  final Duration _delay;

  ScanSessionMockDataSource({Duration? delay})
      : _delay = delay ?? const Duration(milliseconds: 100);

  @override
  Future<ScanSession> get(QueryParams<ScanSession> params) async {
    logger.info('get called');
    await Future<void>.delayed(_delay);
    return ScanSessionMockData.sampleScanSession;
  }
}
''';

const _inSyncMock = '''
// Generated by zfa for: ScanSession
import 'dart:async';

import 'package:zuraffa/mock.dart';
import '../../../domain/entities/scan_session/scan_session.dart';
import '../../mock/scan_session_mock_data.dart';
import 'scan_session_datasource.dart';

class ScanSessionMockDataSource with Loggable, FailureHandler implements ScanSessionDataSource {
  final Duration _delay;

  ScanSessionMockDataSource({Duration? delay})
      : _delay = delay ?? const Duration(milliseconds: 100);

  @override
  Future<ScanSession> get(QueryParams<ScanSession> params) async {
    logger.info('get called');
    await Future<void>.delayed(_delay);
    return ScanSessionMockData.sampleScanSession;
  }

  @override
  Future<List<ScanSession>> getList(ListQueryParams<ScanSession> params) async {
    logger.info('getList called');
    await Future<void>.delayed(_delay);
    return ScanSessionMockData.sampleList;
  }
}
''';

GeneratorConfig _config({
  bool appendToExisting = false,
  bool force = false,
  bool revert = false,
  bool dryRun = false,
}) {
  return GeneratorConfig(
    name: 'ScanSession',
    outputDir: '/tmp/unused-output-dir',
    methods: const ['get', 'getList'],
    generateMock: true,
    generateDataSource: false,
    appendToExisting: appendToExisting,
    force: force,
    revert: revert,
    dryRun: dryRun,
  );
}

/// Seeds the tree: entity + interface declaring get,getList + mock file
/// with [mockContent]. Returns the mock file path.
Future<String> _seedTree(
  String outputDir, {
  required String mockContent,
  String? interfaceContent = _interfaceWithGetList,
}) async {
  final entityDir = Directory('$outputDir/domain/entities/scan_session');
  await entityDir.create(recursive: true);
  await File(
    '${entityDir.path}/scan_session.dart',
  ).writeAsString(_entityFileContent);

  final dsDir = Directory('$outputDir/data/datasources/scan_session');
  await dsDir.create(recursive: true);
  if (interfaceContent != null) {
    await File(
      '${dsDir.path}/scan_session_datasource.dart',
    ).writeAsString(interfaceContent);
  }
  final mockPath = '${dsDir.path}/scan_session_mock_datasource.dart';
  await File(mockPath).writeAsString(mockContent);
  return mockPath;
}

MockDataSourceBuilder _builder(String outputDir) => MockDataSourceBuilder(
  outputDir: outputDir,
  options: const GeneratorOptions(),
  fileSystem: FileSystem.create(),
);

/// Extracts the mock class's implemented member names from a source.
Set<String> _memberNames(String source) {
  final names = <String>{};
  final methodPattern = RegExp(
    r'(?:@override\s+)?(?:Future<[^>]*?(?:<[^>]*>)?>|Stream<[^>]*?(?:<[^>]*>)?>|void)\s+(\w+)\s*\(',
  );
  for (final match in methodPattern.allMatches(source)) {
    names.add(match.group(1)!);
  }
  return names;
}

void main() {
  late Directory tempDir;
  late String outputDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('zuraffa_1570_');
    outputDir = Directory('${tempDir.path}/lib/src').path;
  });

  tearDown(() async {
    if (tempDir.existsSync()) {
      tempDir.deleteSync(recursive: true);
    }
  });

  group('A1/U6 — drifted mock is repaired (issue #1570)', () {
    test(
      'shape drift → repair appends missing member, action updated',
      () async {
        final mockPath = await _seedTree(
          outputDir,
          mockContent: _staleMockWithGetOnly,
        );

        final result = await _builder(
          outputDir,
        ).generateMockDataSource(_config(appendToExisting: false));

        expect(
          result.action,
          'updated',
          reason: 'the drifted mock must be repaired, not skipped',
        );
        final repaired = await File(mockPath).readAsString();
        expect(
          _memberNames(repaired),
          containsAll(['get', 'getList']),
          reason: 'the mock must implement every interface member',
        );
        expect(
          repaired.contains('scan_session_mock_data.dart'),
          isTrue,
          reason: 'repaired file keeps its imports',
        );
        expect(
          repaired.startsWith('// Generated by zfa for: ScanSession'),
          isTrue,
          reason: 'repaired file keeps its provenance header',
        );
      },
    );

    test(
      'through MockPlugin.generate (mock create config shape) heals on disk',
      () async {
        final mockPath = await _seedTree(
          outputDir,
          mockContent: _staleMockWithGetOnly,
        );

        final plugin = MockPlugin(
          outputDir: outputDir,
          options: const GeneratorOptions(),
        );
        final config = GeneratorConfig(
          name: 'ScanSession',
          outputDir: outputDir,
          methods: const ['get', 'getList'],
          generateMock: true,
        );
        final files = await plugin.generate(config);

        final mockFiles = files
            .where((f) => f.type == 'mock_datasource' && f.action != 'skipped')
            .toList();
        expect(
          mockFiles,
          isNotEmpty,
          reason: 'the drifted mock must appear as repaired in the ledger',
        );
        final repaired = await File(mockPath).readAsString();
        expect(_memberNames(repaired), contains('getList'));
      },
    );
  });

  group('A2 — in-sync mock stays skipped', () {
    test(
      'member set covers the interface → skipped, bytes identical',
      () async {
        final mockPath = await _seedTree(outputDir, mockContent: _inSyncMock);
        final before = await File(mockPath).readAsString();

        final result = await _builder(
          outputDir,
        ).generateMockDataSource(_config(appendToExisting: false));

        expect(result.action, 'skipped');
        expect(await File(mockPath).readAsString(), before);
      },
    );
  });

  group('A3 — fail-open when the interface surface is unavailable', () {
    test('missing interface file → skipped, no exception', () async {
      final mockPath = await _seedTree(
        outputDir,
        mockContent: _staleMockWithGetOnly,
        interfaceContent: null,
      );
      final before = await File(mockPath).readAsString();

      final result = await _builder(
        outputDir,
      ).generateMockDataSource(_config(appendToExisting: false));

      expect(result.action, 'skipped');
      expect(await File(mockPath).readAsString(), before);
    });

    test(
      'interface class absent from its file → skipped, no exception',
      () async {
        final mockPath = await _seedTree(
          outputDir,
          mockContent: _staleMockWithGetOnly,
          interfaceContent: 'abstract class SomethingElse { void foo(); }',
        );
        final before = await File(mockPath).readAsString();

        final result = await _builder(
          outputDir,
        ).generateMockDataSource(_config(appendToExisting: false));

        expect(result.action, 'skipped');
        expect(await File(mockPath).readAsString(), before);
      },
    );

    test('mock class absent from its file → skipped, no exception', () async {
      // Fail-open on the mock side too (issue #1570): when the mock
      // file exists but its class cannot be parsed, the lane must NOT
      // fabricate members into a surface it cannot read.
      final mockPath = await _seedTree(
        outputDir,
        mockContent: '// not a mock class: just a comment\n',
      );
      final before = await File(mockPath).readAsString();

      final result = await _builder(
        outputDir,
      ).generateMockDataSource(_config(appendToExisting: false));

      expect(result.action, 'skipped');
      expect(await File(mockPath).readAsString(), before);
    });
  });

  group('A4 — honesty: notice + dry-run safety', () {
    test(
      'repair prints a notice naming entity, missing member and file',
      () async {
        await _seedTree(outputDir, mockContent: _staleMockWithGetOnly);

        final prints = <String>[];
        await runZoned(
          () => _builder(
            outputDir,
          ).generateMockDataSource(_config(appendToExisting: false)),
          zoneSpecification: ZoneSpecification(
            print: (_, _, _, String message) => prints.add(message),
          ),
        );

        final notice = prints.join('\n');
        expect(notice, contains('ScanSession'));
        expect(notice, contains('getList'));
        expect(notice, contains('scan_session_mock_datasource.dart'));
      },
    );

    test('dry-run detects the drift but leaves bytes unchanged', () async {
      final mockPath = await _seedTree(
        outputDir,
        mockContent: _staleMockWithGetOnly,
      );
      final before = await File(mockPath).readAsString();

      // The real pipeline carries the run's dry-run flag on the
      // plugin/builder GeneratorOptions (mirrors FileManager wiring).
      final result = await MockDataSourceBuilder(
        outputDir: outputDir,
        options: const GeneratorOptions(dryRun: true),
        fileSystem: FileSystem.create(),
      ).generateMockDataSource(_config(appendToExisting: false, dryRun: true));

      expect(
        result.action,
        isNot('skipped'),
        reason: 'the ledger must surface the would-be repair',
      );
      expect(
        await File(mockPath).readAsString(),
        before,
        reason: 'dry-run must not change bytes',
      );
    });
  });

  group('U4 — precedence: revert / append-existing / force unchanged', () {
    test('revert still deletes the mock (no shape repair)', () async {
      final mockPath = await _seedTree(
        outputDir,
        mockContent: _staleMockWithGetOnly,
      );

      final result = await _builder(
        outputDir,
      ).generateMockDataSource(_config(appendToExisting: false, revert: true));

      expect(result.action, 'deleted');
      expect(File(mockPath).existsSync(), isFalse);
    });

    test(
      'appendToExisting still idempotently appends (unchanged path)',
      () async {
        final mockPath = await _seedTree(
          outputDir,
          mockContent: _staleMockWithGetOnly,
        );

        final result = await _builder(
          outputDir,
        ).generateMockDataSource(_config(appendToExisting: true));

        expect(result.action, 'overwritten');
        final repaired = await File(mockPath).readAsString();
        expect(_memberNames(repaired), containsAll(['get', 'getList']));
      },
    );

    test('force still fully regenerates (unchanged path)', () async {
      final mockPath = await _seedTree(
        outputDir,
        mockContent: _staleMockWithGetOnly,
      );

      // The real pipeline constructs the plugin/builder with the run's
      // force flag on GeneratorOptions; the fresh path writes with
      // options.force (config.force gates the append decisions).
      final result = await MockDataSourceBuilder(
        outputDir: outputDir,
        options: const GeneratorOptions(force: true),
        fileSystem: FileSystem.create(),
      ).generateMockDataSource(_config(appendToExisting: false, force: true));

      expect(result.action, 'overwritten');
      final regenerated = await File(mockPath).readAsString();
      expect(_memberNames(regenerated), containsAll(['get', 'getList']));
    });
  });

  group('U3 — invented surface is preserved', () {
    test('custom-usecase helper member survives the repair', () async {
      final mockPath = await _seedTree(
        outputDir,
        mockContent: _staleMockWithGetOnly,
      );

      await _builder(
        outputDir,
      ).generateMockDataSource(_config(appendToExisting: false));

      final repaired = await File(mockPath).readAsString();
      expect(
        _memberNames(repaired),
        contains('get'),
        reason: 'pre-existing members are never removed',
      );
      expect(_memberNames(repaired), contains('getList'));
    });
  });
}
