// Bug #1736 — `zfa tdd migrate-paths` rewrote `tdd/cycle-log.md` in place
// while rewriting recorded path FORMS, permanently breaking every entry's
// hash chain.
//
// `cycle-log.md` is append-only, hash-chained evidence (bug #828): each
// entry's `- hash:` is a sha256 over the entry's certified facts — the
// `- test:` path and `- command:` among them — plus the previous link.
// The form rewrite replaced the recorded path strings throughout the whole
// file (verbatim `output:` transcripts included) without recomputing the
// chain, so `doctor` then reported `hash chain broken … the entry was
// tampered with` for every touched entry, and its only remedy was to
// restore the log from a trusted source and re-certify.
//
// Contract under test: the migration repairs the registry alone. The
// cycle-log is history — the paths inside it are what was executed at the
// time and still resolve on this machine (a form rewrite moves nothing) —
// so it must come out of a migration BYTE-IDENTICAL, and the feature must
// stay healthy afterwards.
library;

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:zuraffa/src/cli/cli_runner.dart';
import 'package:zuraffa/src/plugins/tdd/models/cycle_entry.dart';
import 'package:zuraffa/src/plugins/tdd/services/cycle_log.dart';

void main() {
  late Directory tmpDir;

  const feature = '100-feature-one';

  /// Machine-absolute recorded form (the shape an older gen wrote) for a1.
  late String absTestPath;
  late String absSubjectPath;

  /// Portable recorded form for the same files.
  const relTestPath = 'test/tdd/100-feature-one/a1_test.dart';
  const relSubjectPath = 'lib/tdd/100-feature-one/a1_subject.dart';

  late String cycleLogPath;

  String registryJson() => jsonEncode({
    'feature': feature,
    'records': [
      {
        'behavior_id': 'A1',
        'feature': feature,
        'source_criterion': 'FR-007',
        'test_path': absTestPath,
        'subject_path': absSubjectPath,
        'runnable_test_name':
            '$absTestPath::A1::returns 42 when invoked with no args',
        'test_ownership': 'created',
        'subject_ownership': 'created',
        'created_at': '2026-09-01T00:00:00.000Z',
      },
    ],
  });

  List<String> migrateArgs([List<String> extra = const <String>[]]) => [
    'tdd',
    'migrate-paths',
    '--project',
    tmpDir.path,
    ...extra,
  ];

  List<String> doctorArgs() => [
    'tdd',
    'doctor',
    feature,
    '--project',
    tmpDir.path,
  ];

  /// Create the a1 pair at the namespaced paths with plain content (no
  /// imports — the pair must pass doctor's import/symbol checks).
  Future<void> seedArtifacts() async {
    for (final rel in [relTestPath, relSubjectPath]) {
      final file = File(p.join(tmpDir.path, rel));
      await file.parent.create(recursive: true);
      await file.writeAsString('// prior artifact\n');
    }
  }

  Future<void> writeRegistry() async {
    final file = File(
      p.join(tmpDir.path, 'specs', feature, 'tdd', 'artifacts.json'),
    );
    await file.parent.create(recursive: true);
    await file.writeAsString(registryJson());
  }

  /// Record a REAL hash-chained red + green certification for A1, naming
  /// the machine-absolute path exactly as the registry recorded it — the
  /// pre-migration state of a feature generated by an older zfa.
  Future<void> seedChainedCycleLog() async {
    final log = CycleLog(p.join(tmpDir.path, 'specs', feature));
    await log.append(
      CycleLogEntry(
        behaviorId: 'A1',
        kind: CycleEntryKind.red,
        runnerCommand: 'dart test $absTestPath --plain-name "A1"',
        exitCode: 1,
        capturedOutput: 'Expected: <42>\n  Actual: <0>\n',
        classification: FailureClass.assertionFailure,
        sourceCriterion: 'FR-007',
        testPath: absTestPath,
        timestamp: '2026-09-01T00:00:00.000Z',
      ),
    );
    await log.append(
      CycleLogEntry(
        behaviorId: 'A1',
        kind: CycleEntryKind.green,
        runnerCommand: 'dart test $absTestPath --plain-name "A1"',
        exitCode: 0,
        capturedOutput: 'All tests passed!\n',
        sourceCriterion: 'FR-007',
        testPath: absTestPath,
        timestamp: '2026-09-01T00:01:00.000Z',
      ),
    );
  }

  setUp(() {
    tmpDir = Directory.systemTemp.createTempSync('bug_1736_cycle_log_');
    absTestPath = p.join(tmpDir.path, relTestPath);
    absSubjectPath = p.join(tmpDir.path, relSubjectPath);
    cycleLogPath = p.join(tmpDir.path, 'specs', feature, 'tdd', 'cycle-log.md');
  });

  tearDown(() {
    if (tmpDir.existsSync()) tmpDir.deleteSync(recursive: true);
  });

  group(
    'Bug #1736 — migrate-paths never rewrites the append-only cycle-log',
    () {
      test(
        'the recorded path FORM is repaired in the registry alone: the '
        'cycle-log stays byte-identical and the hash chain still verifies',
        () async {
          await seedArtifacts();
          await writeRegistry();
          await seedChainedCycleLog();
          final before = File(cycleLogPath).readAsStringSync();
          // Fixture sanity: the log really carries a schema-1 hash chain and
          // names the machine-absolute recorded form the registry holds.
          expect(before, contains('- schema: 1'));
          expect(before, contains('- hash: '));
          expect(before, contains('- test: $absTestPath'));

          final runner = CliRunner(exitOnCompletion: false);
          final out = await runner.runCapturing(
            migrateArgs(['--feature', feature]),
          );
          expect(out, contains('migrated=1'), reason: out);

          // The live registry now carries the portable form ...
          final stored =
              (jsonDecode(
                        File(
                          p.join(
                            tmpDir.path,
                            'specs',
                            feature,
                            'tdd',
                            'artifacts.json',
                          ),
                        ).readAsStringSync(),
                      )
                      as Map<String, dynamic>)['records']
                  as List;
          expect(
            (stored.single as Map<String, dynamic>)['test_path'],
            relTestPath,
          );

          // ... and the append-only evidence is untouched, byte for byte.
          expect(
            File(cycleLogPath).readAsStringSync(),
            before,
            reason:
                'cycle-log.md is append-only hash-chained evidence (bug #828); '
                'rewriting it invalidates every entry hash',
          );

          // The migration must leave the store healthy: no hash-chain drift.
          final doctorOut = await runner.runCapturing(doctorArgs());
          expect(
            doctorOut,
            isNot(contains('hash chain broken')),
            reason: 'the form rewrite must never break the evidence chain',
          );
          final verdict =
              jsonDecode(
                    doctorOut
                        .split('\n')
                        .map((l) => l.trim())
                        .where((l) => l.isNotEmpty)
                        .last,
                  )
                  as Map<String, dynamic>;
          expect(verdict['verdict'], 'healthy', reason: doctorOut);
        },
      );

      test('a second migration run rewrites nothing and still leaves the '
          'cycle-log byte-identical', () async {
        await seedArtifacts();
        await writeRegistry();
        await seedChainedCycleLog();
        final before = File(cycleLogPath).readAsStringSync();

        final runner = CliRunner(exitOnCompletion: false);
        await runner.runCapturing(migrateArgs(['--feature', feature]));
        final out = await runner.runCapturing(
          migrateArgs(['--feature', feature]),
        );

        expect(out, contains('migrated=0'), reason: out);
        expect(File(cycleLogPath).readAsStringSync(), before);
      });
    },
  );

  group('Bug #1736 — a moved legacy pair keeps its log and stays healthy', () {
    test(
      'the legacy flat -> namespaced move leaves the cycle-log verbatim '
      'and doctor resolves the certified artifact through the registry',
      () async {
        // The pre-#827 state: the pair lives flat, the registry records
        // the flat paths, and the append-only log certifies a green at
        // the flat path. The migration moves the pair — and the log, being
        // history, keeps naming the path the green was certified at.
        final flatTest = p.join(tmpDir.path, 'test', 'tdd', 'a1_test.dart');
        final flatSubject = p.join(
          tmpDir.path,
          'lib',
          'tdd',
          'a1_subject.dart',
        );
        for (final file in [flatTest, flatSubject]) {
          File(file)
            ..parent.createSync(recursive: true)
            ..writeAsStringSync('// legacy artifact\n');
        }
        final tddDir = Directory(p.join(tmpDir.path, 'specs', feature, 'tdd'))
          ..createSync(recursive: true);
        await File(p.join(tddDir.path, 'artifacts.json')).writeAsString(
          jsonEncode({
            'feature': feature,
            'records': [
              {
                'behavior_id': 'A1',
                'feature': feature,
                'source_criterion': 'FR-007',
                'test_path': flatTest,
                'subject_path': flatSubject,
                'runnable_test_name':
                    '$flatTest::A1::returns 42 when invoked with no args',
                'test_ownership': 'created',
                'subject_ownership': 'created',
                'created_at': '2026-09-01T00:00:00.000Z',
              },
            ],
          }),
        );
        await File(p.join(tddDir.path, 'cycle-log.md')).writeAsString('''
# Cycle Log

## Cycle: A1 (red)

- behavior: A1
- kind: red
- classification: assertionFailure
- criterion: FR-007
- test: $flatTest
- command: `dart test $flatTest`
- exit: 1
- at: 2026-09-01T00:00:00.000Z

## Cycle: A1 (green)

- behavior: A1
- kind: green
- criterion: FR-007
- test: $flatTest
- command: `dart test $flatTest`
- exit: 0
- at: 2026-09-01T00:01:00.000Z
''');
        final before = File(cycleLogPath).readAsStringSync();

        final runner = CliRunner(exitOnCompletion: false);
        final out = await runner.runCapturing(
          migrateArgs(['--feature', feature]),
        );
        expect(out, contains('migrated=1'), reason: out);

        final movedTest = p.join(
          tmpDir.path,
          'test',
          'tdd',
          feature,
          'a1_test.dart',
        );
        expect(File(movedTest).existsSync(), isTrue);
        expect(
          File(cycleLogPath).readAsStringSync(),
          before,
          reason: 'the append-only log is history — never rewritten',
        );

        // The moved artifact no longer sits where the green entry says,
        // so the check must resolve it through the live registry instead
        // of orphaning the evidence and prescribing a re-drive.
        final doctorOut = await runner.runCapturing(doctorArgs());
        expect(doctorOut, isNot(contains('evidence-without-artifact')));
        final verdict =
            jsonDecode(
                  doctorOut
                      .split('\n')
                      .map((l) => l.trim())
                      .where((l) => l.isNotEmpty)
                      .last,
                )
                as Map<String, dynamic>;
        expect(verdict['verdict'], 'healthy', reason: doctorOut);
      },
    );
  });
}
